import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { type Config, loadConfig } from "../src/config"
import { drift, readPlugins, render, write } from "../src/generate"
import { createFakeContext } from "../src/testing"
import { cleanup, fixtureCopy } from "./helpers"

const RUNTIME = path.join(import.meta.dir, "..", "runtime")
const HEADER = "// Generated by scripts/build.ts. Do not edit.\n"

let root: string
let config: Config
beforeEach(() => {
  root = fixtureCopy()
  config = loadConfig(root)
})
afterEach(cleanup)

const demo = (file: string) => path.join(root, "plugins", "demo", file)
const read = (file: string) => readFileSync(demo(file), "utf8")
const source = (harness: string, file: string) => readFileSync(path.join(RUNTIME, harness, file), "utf8")
const generate = () => write(root, render(root, readPlugins(root, config), config), config)
const stale = () => {
  const found = drift(root, render(root, readPlugins(root, config), config), config)
  return [...found.changed, ...found.extra].map((file) => path.relative(path.join(root, "plugins", "demo"), file)).sort()
}
const editManifest = (change: (own: any, manifest: any) => void) => {
  const manifest = JSON.parse(read("package.json"))
  change(manifest["agent-plugins"], manifest)
  writeFileSync(demo("package.json"), JSON.stringify(manifest))
}
const optIn = (runtime: unknown = true) => editManifest((own) => (own.runtime = runtime))

describe("opting in", () => {
  test("a plugin that does not opt in gets no _kit directory in any harness tree", () => {
    generate()
    for (const harness of ["opencode", "claude", "omp"]) expect(existsSync(demo(`${harness}/_kit`))).toBe(false)
  })

  test("runtime: true vendors every module of each listed harness, behind a generated-by header", () => {
    optIn()
    generate()
    const expected: Array<[string, string, string]> = [
      ["opencode/_kit/frontmatter.ts", "opencode", "frontmatter.ts"],
      ["opencode/_kit/content.ts", "opencode", "content.ts"],
      ["opencode/_kit/agents.ts", "opencode", "agents.ts"],
      ["opencode/_kit/session.ts", "opencode", "session.ts"],
      ["claude/_kit/render.mjs", "claude", "render.mjs"],
      ["omp/_kit/template-extension.ts", "omp", "template-extension.ts"],
    ]
    for (const [file, harness, name] of expected) expect(read(file)).toBe(HEADER + source(harness, name))
    expect(stale()).toEqual([])
  })

  test("a list vendors those modules plus their dependencies and nothing else", () => {
    optIn(["content"])
    generate()
    expect(existsSync(demo("opencode/_kit/content.ts"))).toBe(true)
    expect(existsSync(demo("opencode/_kit/frontmatter.ts"))).toBe(true)
    expect(existsSync(demo("opencode/_kit/session.ts"))).toBe(false)
    expect(existsSync(demo("claude/_kit"))).toBe(false)
    expect(existsSync(demo("omp/_kit"))).toBe(false)
  })

  test("runtime: true skips the harnesses the plugin does not list", () => {
    editManifest((own) => {
      own.harnesses = ["claude"]
      own.runtime = true
    })
    for (const harness of ["opencode", "omp"]) rmSync(demo(harness), { recursive: true })
    generate()
    expect(existsSync(demo("claude/_kit/render.mjs"))).toBe(true)
    expect(existsSync(demo("opencode"))).toBe(false)
  })

  test("the header names the generator from the config", () => {
    config.generatedBy = "harness-kit build"
    optIn(["session"])
    generate()
    expect(read("opencode/_kit/session.ts").startsWith("// Generated by harness-kit build. Do not edit.\n")).toBe(true)
  })

  test("inventory.json records the vendored modules, and the inventory kinds do not change", () => {
    optIn()
    generate()
    const entry = JSON.parse(readFileSync(path.join(root, "inventory.json"), "utf8")).plugins[0]
    expect(entry.runtime).toEqual(["frontmatter", "content", "agents", "session", "render", "template-extension"])
    expect(entry.harnesses.opencode.extensions).toEqual(["index", "tui"])
    expect(entry.harnesses.omp.extensions).toEqual(["demo-ext"])
  })
})

describe("drift", () => {
  test("a hand-edited vendored file is stale", () => {
    optIn()
    generate()
    writeFileSync(demo("opencode/_kit/content.ts"), "// edited\n")
    expect(stale()).toEqual(["opencode/_kit/content.ts"])
  })

  test("a file added to _kit by hand is stale, and build removes it", () => {
    optIn()
    generate()
    writeFileSync(demo("opencode/_kit/extra.ts"), "x")
    expect(stale()).toEqual(["opencode/_kit/extra.ts"])
    generate()
    expect(existsSync(demo("opencode/_kit/extra.ts"))).toBe(false)
  })

  test("opting out again removes the vendored files and leaves no empty _kit directory", () => {
    optIn()
    generate()
    editManifest((own) => delete own.runtime)
    expect(stale()).toContain("opencode/_kit/content.ts")
    generate()
    for (const harness of ["opencode", "claude", "omp"]) expect(existsSync(demo(`${harness}/_kit`))).toBe(false)
    expect(stale()).toEqual([])
  })

  test("a list narrowed to fewer modules removes the dropped ones", () => {
    optIn()
    generate()
    optIn(["session"])
    generate()
    expect(existsSync(demo("opencode/_kit/session.ts"))).toBe(true)
    expect(existsSync(demo("opencode/_kit/content.ts"))).toBe(false)
    expect(existsSync(demo("claude/_kit"))).toBe(false)
  })
})

describe("validation", () => {
  test.each([
    ["an unknown module", ["nope"], /unknown runtime module "nope"/],
    ["an empty list", [], /must be true or a non-empty list/],
    ["a non-string entry", [3], /must be true or a non-empty list/],
    ["a string", "content", /must be true or a non-empty list/],
  ])("rejects %s", (_label, runtime, message) => {
    optIn(runtime)
    expect(() => readPlugins(root, config)).toThrow(message)
  })

  test("rejects a module for a harness the plugin does not list", () => {
    editManifest((own) => {
      own.harnesses = ["opencode"]
      own.runtime = ["render"]
    })
    for (const harness of ["claude", "omp"]) rmSync(demo(harness), { recursive: true })
    expect(() => readPlugins(root, config)).toThrow(/"render" is for claude/)
  })

  test("runtime: false is the same as leaving it out", () => {
    optIn(false)
    expect(readPlugins(root, config)[0]?.runtime).toBeUndefined()
  })

  test("commonDirs cannot list _kit", () => {
    expect(() => loadConfigWith({ commonDirs: ["skills", "_kit"] })).toThrow(/_kit/)
  })
})

function loadConfigWith(extra: Record<string, unknown>) {
  const dir = fixtureCopy()
  const raw = JSON.parse(readFileSync(path.join(dir, "harness-kit.json"), "utf8"))
  writeFileSync(path.join(dir, "harness-kit.json"), JSON.stringify({ ...raw, ...extra }))
  return loadConfig(dir)
}

describe("the vendored copies work on their own", () => {
  test("OpenCode content: the vendored content.ts registers the tree's skills and system text", async () => {
    optIn(["content"])
    generate()
    const tree = demo("opencode")
    const vendored = (await import(path.join(tree, "_kit", "content.ts"))) as typeof import("../runtime/opencode/content.ts")
    const host = createFakeContext()
    const dispose = await vendored.setupContent(host.ctx, { root: tree })
    expect([...host.skills.keys()]).toEqual(["demo-skill"])
    expect(host.system).toHaveLength(1)
    expect(host.system[0]?.text).toContain("# Demo rule")
    expect(host.system[0]?.text).toContain("Say hello.")
    await dispose()
    expect(host.disposed()).toBe(2)
  })

  test("setupContent defaults the root to the parent of _kit", async () => {
    optIn(["content"])
    generate()
    const tree = demo("opencode")
    const vendored = (await import(path.join(tree, "_kit", "content.ts"))) as typeof import("../runtime/opencode/content.ts")
    const host = createFakeContext()
    await vendored.setupContent(host.ctx)
    expect([...host.skills.keys()]).toEqual(["demo-skill"])
  })

  test("Claude render.mjs prints the named template with the env option, falling back to the default", () => {
    optIn(["render"])
    generate()
    const run = (env: Record<string, string>) =>
      Bun.spawnSync([process.execPath, demo("claude/_kit/render.mjs"), "demo-template"], { env: { PATH: process.env.PATH ?? "", ...env }, stdout: "pipe" }).stdout.toString()
    expect(run({})).toBe("# Demo template\n\nSay hello.\n")
    expect(run({ CLAUDE_PLUGIN_OPTION_GREETING: "hi" })).toBe("# Demo template\n\nSay hi.\n")
    expect(run({ CLAUDE_PLUGIN_OPTION_GREETING: "" })).toBe("# Demo template\n\nSay hello.\n")
  })
})

describe("agent registration (vendored agents.ts)", () => {
  const load = async () => {
    optIn(["agents"])
    generate()
    expect(existsSync(demo("opencode/_kit/frontmatter.ts"))).toBe(true)
    return (await import(path.join(demo("opencode"), "_kit", "agents.ts"))) as typeof import("../runtime/opencode/agents.ts")
  }
  const writeAgent = (name: string, text: string) => {
    mkdirSync(demo("opencode/agents"), { recursive: true })
    writeFileSync(demo(`opencode/agents/${name}.md`), text)
  }

  test("loadAgentFiles reads agents/*.md in name order with front matter fields and the prompt", async () => {
    const { loadAgentFiles } = await load()
    writeAgent("b", "---\ndescription: Second.\nmode: subagent\n---\n\nPrompt B\n")
    writeAgent("a", "No front matter\n")
    const files = loadAgentFiles(demo("opencode"))
    expect(files.map((file) => file.id)).toEqual(["a", "b"])
    expect(files[1]?.field("description")).toBe("Second.")
    expect(files[1]?.system).toBe("Prompt B")
    expect(files[0]?.system).toBe("No front matter")
  })

  test("a new agent is registered with its description, mode and prompt", async () => {
    const { loadAgentFiles, registerAgents } = await load()
    writeAgent("a", "---\ndescription: First.\nmode: subagent\n---\nPrompt A\n")
    const host = createFakeContext()
    const registration = await registerAgents(host.ctx.agent, loadAgentFiles(demo("opencode")), { debug: () => {} })
    expect(host.agents.get("a")).toEqual({ description: "First.", mode: "subagent", system: "Prompt A" })
    expect(registration.skipped).toEqual([])
    await registration.dispose()
    expect(host.disposed()).toBe(1)
  })

  test("an agent that another plugin already registered is skipped with one debug line, so the first plugin wins", async () => {
    const { loadAgentFiles, registerAgents } = await load()
    writeAgent("a", "---\ndescription: Version 2.\n---\nPrompt v2\n")
    const host = createFakeContext()
    host.agents.set("a", { description: "Version 1.", system: "Prompt v1" })
    const lines: string[] = []
    const registration = await registerAgents(host.ctx.agent, loadAgentFiles(demo("opencode")), { debug: (line) => void lines.push(line) })
    expect(host.agents.get("a")).toEqual({ description: "Version 1.", system: "Prompt v1" })
    expect(registration.skipped).toEqual(["a"])
    expect(lines).toHaveLength(1)
    expect(lines[0]).toContain('agent "a" is already registered by another plugin')
  })

  test("two plugins on one host: the second skips only the agents the first registered", async () => {
    const { loadAgentFiles, registerAgents } = await load()
    writeAgent("shared", "---\ndescription: Shared.\n---\nOne\n")
    const host = createFakeContext()
    await registerAgents(host.ctx.agent, loadAgentFiles(demo("opencode")), { debug: () => {} })
    writeAgent("shared", "---\ndescription: Shared.\n---\nTwo\n")
    writeAgent("extra", "---\ndescription: Extra.\n---\nExtra prompt\n")
    const second = await registerAgents(host.ctx.agent, loadAgentFiles(demo("opencode")), { debug: () => {} })
    expect(second.skipped).toEqual(["shared"])
    expect(host.agents.get("shared")?.system).toBe("One")
    expect(host.agents.get("extra")?.system).toBe("Extra prompt")
  })

  test("a custom apply shapes the draft of a new agent only", async () => {
    const { loadAgentFiles, registerAgents } = await load()
    writeAgent("a", "Prompt\n")
    writeAgent("b", "Prompt\n")
    const host = createFakeContext({ existingAgents: ["b"] })
    await registerAgents(host.ctx.agent, loadAgentFiles(demo("opencode")), {
      debug: () => {},
      apply: (draft, file) => void (draft.shaped = file.id),
    })
    expect(host.agents.get("a")).toEqual({ shaped: "a" })
    expect(host.agents.get("b")).toEqual({ system: "own" })
  })

  describe("owner-wins mode", () => {
    const FALLBACK_HEADER = "x-fallback"
    const MATCH = { idPrefix: "acme.", packagePrefixes: ["plug-"] }
    const owners = { a: "agent-a" }
    const listing = (list: () => Promise<unknown>) => ({ list })
    const installed = listing(async () => ({ data: [{ id: "acme.agent-a" }] }))
    const absent = listing(async () => ({ data: [] }))
    const setup = async (prompt = "Prompt") => {
      const mod = await load()
      writeAgent("a", `---\ndescription: Owner.\nmode: subagent\n---\n${prompt}\n`)
      writeAgent("b", "Other\n")
      return { ...mod, files: mod.loadAgentFiles(demo("opencode")) }
    }
    const fallback = (plugin: { list(): Promise<unknown> }, extra = {}) => ({ owners, plugin, pluginMatch: MATCH, debug: () => {}, ...extra })
    const owner = (extra = {}) => ({ role: "owner" as const, fallbackHeader: FALLBACK_HEADER, debug: () => {}, ...extra })
    const copyDraft = {
      system: "Prompt",
      description: "stale",
      mode: "primary",
      model: { id: "m" },
      permissions: [{ action: "read" }],
      request: { headers: { "x-role": "standard", [FALLBACK_HEADER]: "p/m" } },
    }

    test("fallback skips its copy when the owner is installed, and registers the unowned agents", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      const registration = await registerAgents(host.ctx.agent, files, fallback(installed))
      expect([...host.agents.keys()]).toEqual(["b"])
      expect(registration.skipped).toEqual(["a"])
    })

    test("fallback registers its copy when the owner is absent", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, fallback(absent))
      expect(host.agents.get("a")?.system).toBe("Prompt")
    })

    test("fallback never replaces an existing owned id, even when the owner is not listed", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext({ existingAgents: ["a"] })
      const registration = await registerAgents(host.ctx.agent, files, fallback(absent))
      expect(host.agents.get("a")).toEqual({ system: "own" })
      expect(registration.skipped).toEqual(["a"])
    })

    test.each([
      ["rejects", async () => Promise.reject(new Error("down"))],
      ["never answers", () => new Promise<unknown>(() => {})],
    ])("fallback treats plugin.list that %s as owner not installed", async (_name, list) => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, fallback({ list }, { listTimeoutMs: 5 }))
      expect(host.agents.get("a")?.system).toBe("Prompt")
    })

    test("fallback without a plugin host cannot see the owner and registers its copy", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, { owners, debug: () => {} })
      expect(host.agents.has("a")).toBe(true)
    })

    test("fallback does not call plugin.list when no file is owned", async () => {
      const { files, registerAgents } = await setup()
      let calls = 0
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, fallback(listing(async () => void calls++), { owners: { zzz: "agent-a" } }))
      expect(calls).toBe(0)
    })

    test.each([
      ["id", { id: "acme.agent-a" }],
      ["package target", { source: { target: "@scope/plug-agent-a" } }],
      ["bare package target", { source: { target: "agent-a" } }],
      ["versioned package target", { source: { target: "@scope/plug-agent-a@1.2.3" } }],
      ["git target with ref and path", { source: { target: "github:owner/repo#main::path:plugins/agent-a" } }],
      ["local path file", { source: { path: "/x/plugins/agent-a.js" } }],
      ["local path", { source: { path: "/x/plugins/agent-a/index.js" } }],
    ])("an owner listed by %s counts as installed", async (_name, entry) => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, fallback(listing(async () => [entry])))
      expect(host.agents.has("a")).toBe(false)
    })

    test.each([
      ["a different id prefix", { id: "other.agent-a" }],
      ["a longer name", { source: { target: "@scope/agent-ab" } }],
      ["a hyphen-suffixed id", { id: "acme.agent-a-extra" }],
      ["a hyphen-suffixed package target", { source: { target: "@scope/agent-a-extra" } }],
      ["a hyphen-suffixed prefixed target", { source: { target: "@scope/plug-agent-a-extra@1.0.0" } }],
      ["a hyphen-suffixed local path", { source: { path: "/x/plugins/agent-a-extra/index.js" } }],
      ["an unrelated plugin", { id: "acme.delivery", source: { target: "x/delivery" } }],
    ])("%s does not count as the owner", async (_name, entry) => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, fallback(listing(async () => [entry])))
      expect(host.agents.has("a")).toBe(true)
    })

    test("owner replaces a fallback copy with a fresh registration", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      host.agents.set("a", structuredClone(copyDraft))
      const registration = await registerAgents(host.ctx.agent, files, owner())
      expect(host.agents.get("a")).toEqual({
        system: "Prompt",
        description: "Owner.",
        mode: "subagent",
        permissions: [],
        request: { headers: { "x-role": "standard" } },
      })
      expect(registration.replaced).toEqual(["a"])
      expect(registration.skipped).toEqual([])
    })

    test("owner replaces a copy without request headers", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      host.agents.set("a", { system: "Prompt", model: { id: "m" } })
      await registerAgents(host.ctx.agent, files, owner())
      expect(host.agents.get("a")?.model).toBeUndefined()
      expect(host.agents.get("a")?.request).toBeUndefined()
    })

    test("owner layers over an agent with a different prompt and keeps its fields", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      host.agents.set("a", { system: "mine", description: "Mine.", mode: "primary", model: { id: "m" } })
      const registration = await registerAgents(host.ctx.agent, files, owner())
      expect(host.agents.get("a")).toEqual({ system: "mine", description: "Mine.", mode: "primary", model: { id: "m" } })
      expect(registration.replaced).toEqual([])
    })

    test("owner layers over an agent with a different prompt: fills missing metadata, keeps existing fields", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      host.agents.set("a", { system: "mine", model: { id: "m" } })
      await registerAgents(host.ctx.agent, files, owner())
      expect(host.agents.get("a")).toEqual({ system: "mine", model: { id: "m" }, description: "Owner.", mode: "subagent" })
    })

    test("owner registers a new agent normally", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      await registerAgents(host.ctx.agent, files, owner())
      expect(host.agents.get("a")).toEqual({ description: "Owner.", mode: "subagent", system: "Prompt" })
    })

    test("a custom apply on the owner side receives created=false for layering and true for a replaced copy", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      host.agents.set("a", { system: "Prompt" })
      host.agents.set("b", { system: "mine" })
      const seen: string[] = []
      await registerAgents(host.ctx.agent, files, owner({ apply: (_d: unknown, file: { id: string }, created: boolean) => void seen.push(`${file.id}:${created}`) }))
      expect(seen).toEqual(["a:true", "b:false"])
    })

    test.each(["fallback first", "owner first"])("either load order leaves one agent with the owner's fields: %s", async (order) => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext()
      const runFallback = () => registerAgents(host.ctx.agent, files, fallback(absent))
      const runOwner = () => registerAgents(host.ctx.agent, files, owner())
      if (order === "fallback first") {
        await runFallback()
        await runOwner()
      } else {
        await runOwner()
        await runFallback()
      }
      expect(host.agents.get("a")).toEqual({ description: "Owner.", mode: "subagent", system: "Prompt" })
    })

    test("debug accepts a host logger object", async () => {
      const { files, registerAgents } = await setup()
      const host = createFakeContext({ existingAgents: ["a"] })
      const lines: string[] = []
      await registerAgents(host.ctx.agent, files, { debug: { debug: (line: string) => void lines.push(line) } })
      expect(lines).toHaveLength(1)
    })
  })
})
