import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { type Config, loadConfig } from "../src/config"
import { drift, readPlugins, render, write } from "../src/generate"
import { createFakeContext } from "../src/testing"
import { cleanup, fixtureCopy } from "./helpers"

const RUNTIME = path.join(import.meta.dir, "..", "runtime")
const HEADER = "// Generated by scripts/build.ts. Do not edit.\n"

let root: string
let config: Config
beforeEach(() => {
  root = fixtureCopy()
  config = loadConfig(root)
})
afterEach(cleanup)

const demo = (file: string) => path.join(root, "plugins", "demo", file)
const read = (file: string) => readFileSync(demo(file), "utf8")
const source = (harness: string, file: string) => readFileSync(path.join(RUNTIME, harness, file), "utf8")
const generate = () => write(root, render(root, readPlugins(root, config), config), config)
const stale = () => {
  const found = drift(root, render(root, readPlugins(root, config), config), config)
  return [...found.changed, ...found.extra].map((file) => path.relative(path.join(root, "plugins", "demo"), file)).sort()
}
const editManifest = (change: (own: any, manifest: any) => void) => {
  const manifest = JSON.parse(read("package.json"))
  change(manifest["agent-plugins"], manifest)
  writeFileSync(demo("package.json"), JSON.stringify(manifest))
}
const optIn = (runtime: unknown = true) => editManifest((own) => (own.runtime = runtime))

describe("opting in", () => {
  test("a plugin that does not opt in gets no _kit directory in any harness tree", () => {
    generate()
    for (const harness of ["opencode", "claude", "omp"]) expect(existsSync(demo(`${harness}/_kit`))).toBe(false)
  })

  test("runtime: true vendors every module of each listed harness, behind a generated-by header", () => {
    optIn()
    generate()
    const expected: Array<[string, string, string]> = [
      ["opencode/_kit/frontmatter.ts", "opencode", "frontmatter.ts"],
      ["opencode/_kit/content.ts", "opencode", "content.ts"],
      ["opencode/_kit/session.ts", "opencode", "session.ts"],
      ["claude/_kit/render.mjs", "claude", "render.mjs"],
      ["omp/_kit/template-extension.ts", "omp", "template-extension.ts"],
    ]
    for (const [file, harness, name] of expected) expect(read(file)).toBe(HEADER + source(harness, name))
    expect(stale()).toEqual([])
  })

  test("a list vendors those modules plus their dependencies and nothing else", () => {
    optIn(["content"])
    generate()
    expect(existsSync(demo("opencode/_kit/content.ts"))).toBe(true)
    expect(existsSync(demo("opencode/_kit/frontmatter.ts"))).toBe(true)
    expect(existsSync(demo("opencode/_kit/session.ts"))).toBe(false)
    expect(existsSync(demo("claude/_kit"))).toBe(false)
    expect(existsSync(demo("omp/_kit"))).toBe(false)
  })

  test("runtime: true skips the harnesses the plugin does not list", () => {
    editManifest((own) => {
      own.harnesses = ["claude"]
      own.runtime = true
    })
    for (const harness of ["opencode", "omp"]) rmSync(demo(harness), { recursive: true })
    generate()
    expect(existsSync(demo("claude/_kit/render.mjs"))).toBe(true)
    expect(existsSync(demo("opencode"))).toBe(false)
  })

  test("the header names the generator from the config", () => {
    config.generatedBy = "harness-kit build"
    optIn(["session"])
    generate()
    expect(read("opencode/_kit/session.ts").startsWith("// Generated by harness-kit build. Do not edit.\n")).toBe(true)
  })

  test("inventory.json records the vendored modules, and the inventory kinds do not change", () => {
    optIn()
    generate()
    const entry = JSON.parse(readFileSync(path.join(root, "inventory.json"), "utf8")).plugins[0]
    expect(entry.runtime).toEqual(["frontmatter", "content", "session", "render", "template-extension"])
    expect(entry.harnesses.opencode.extensions).toEqual(["index", "tui"])
    expect(entry.harnesses.omp.extensions).toEqual(["demo-ext"])
  })
})

describe("drift", () => {
  test("a hand-edited vendored file is stale", () => {
    optIn()
    generate()
    writeFileSync(demo("opencode/_kit/content.ts"), "// edited\n")
    expect(stale()).toEqual(["opencode/_kit/content.ts"])
  })

  test("a file added to _kit by hand is stale, and build removes it", () => {
    optIn()
    generate()
    writeFileSync(demo("opencode/_kit/extra.ts"), "x")
    expect(stale()).toEqual(["opencode/_kit/extra.ts"])
    generate()
    expect(existsSync(demo("opencode/_kit/extra.ts"))).toBe(false)
  })

  test("opting out again removes the vendored files and leaves no empty _kit directory", () => {
    optIn()
    generate()
    editManifest((own) => delete own.runtime)
    expect(stale()).toContain("opencode/_kit/content.ts")
    generate()
    for (const harness of ["opencode", "claude", "omp"]) expect(existsSync(demo(`${harness}/_kit`))).toBe(false)
    expect(stale()).toEqual([])
  })

  test("a list narrowed to fewer modules removes the dropped ones", () => {
    optIn()
    generate()
    optIn(["session"])
    generate()
    expect(existsSync(demo("opencode/_kit/session.ts"))).toBe(true)
    expect(existsSync(demo("opencode/_kit/content.ts"))).toBe(false)
    expect(existsSync(demo("claude/_kit"))).toBe(false)
  })
})

describe("validation", () => {
  test.each([
    ["an unknown module", ["nope"], /unknown runtime module "nope"/],
    ["an empty list", [], /must be true or a non-empty list/],
    ["a non-string entry", [3], /must be true or a non-empty list/],
    ["a string", "content", /must be true or a non-empty list/],
  ])("rejects %s", (_label, runtime, message) => {
    optIn(runtime)
    expect(() => readPlugins(root, config)).toThrow(message)
  })

  test("rejects a module for a harness the plugin does not list", () => {
    editManifest((own) => {
      own.harnesses = ["opencode"]
      own.runtime = ["render"]
    })
    for (const harness of ["claude", "omp"]) rmSync(demo(harness), { recursive: true })
    expect(() => readPlugins(root, config)).toThrow(/"render" is for claude/)
  })

  test("runtime: false is the same as leaving it out", () => {
    optIn(false)
    expect(readPlugins(root, config)[0]?.runtime).toBeUndefined()
  })

  test("commonDirs cannot list _kit", () => {
    expect(() => loadConfigWith({ commonDirs: ["skills", "_kit"] })).toThrow(/_kit/)
  })
})

function loadConfigWith(extra: Record<string, unknown>) {
  const dir = fixtureCopy()
  const raw = JSON.parse(readFileSync(path.join(dir, "harness-kit.json"), "utf8"))
  writeFileSync(path.join(dir, "harness-kit.json"), JSON.stringify({ ...raw, ...extra }))
  return loadConfig(dir)
}

describe("the vendored copies work on their own", () => {
  test("OpenCode content: the vendored content.ts registers the tree's skills and system text", async () => {
    optIn(["content"])
    generate()
    const tree = demo("opencode")
    const vendored = (await import(path.join(tree, "_kit", "content.ts"))) as typeof import("../runtime/opencode/content.ts")
    const host = createFakeContext()
    const dispose = await vendored.setupContent(host.ctx, { root: tree })
    expect([...host.skills.keys()]).toEqual(["demo-skill"])
    expect(host.system).toHaveLength(1)
    expect(host.system[0]?.text).toContain("# Demo rule")
    expect(host.system[0]?.text).toContain("Say hello.")
    await dispose()
    expect(host.disposed()).toBe(2)
  })

  test("setupContent defaults the root to the parent of _kit", async () => {
    optIn(["content"])
    generate()
    const tree = demo("opencode")
    const vendored = (await import(path.join(tree, "_kit", "content.ts"))) as typeof import("../runtime/opencode/content.ts")
    const host = createFakeContext()
    await vendored.setupContent(host.ctx)
    expect([...host.skills.keys()]).toEqual(["demo-skill"])
  })

  test("Claude render.mjs prints the named template with the env option, falling back to the default", () => {
    optIn(["render"])
    generate()
    const run = (env: Record<string, string>) =>
      Bun.spawnSync([process.execPath, demo("claude/_kit/render.mjs"), "demo-template"], { env: { PATH: process.env.PATH ?? "", ...env }, stdout: "pipe" }).stdout.toString()
    expect(run({})).toBe("# Demo template\n\nSay hello.\n")
    expect(run({ CLAUDE_PLUGIN_OPTION_GREETING: "hi" })).toBe("# Demo template\n\nSay hi.\n")
    expect(run({ CLAUDE_PLUGIN_OPTION_GREETING: "" })).toBe("# Demo template\n\nSay hello.\n")
  })
})
