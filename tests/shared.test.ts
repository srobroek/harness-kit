import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { type Config, loadConfig } from "../src/config"
import { drift, readPlugins, render, write } from "../src/generate"
import { cleanup, fixtureCopy } from "./helpers"

let root: string
let config: Config
beforeEach(() => {
  root = fixtureCopy()
  config = loadConfig(root)
  config.commonDirs = [...config.commonDirs, "agents"]
})
afterEach(cleanup)

const AGENT = "---\nname: challenger\ndescription: Argues the other side.\n---\nYou challenge claims.\n"
const put = (file: string, text: string) => {
  mkdirSync(path.dirname(path.join(root, file)), { recursive: true })
  writeFileSync(path.join(root, file), text)
}
const read = (file: string) => readFileSync(path.join(root, file), "utf8")
const exists = (file: string) => existsSync(path.join(root, file))
const generate = () => write(root, render(root, readPlugins(root, config), config), config)
const stale = () => {
  const found = drift(root, render(root, readPlugins(root, config), config), config)
  return [...found.changed, ...found.extra].map((file) => path.relative(root, file)).sort()
}
const takes = (...items: string[]) => {
  const manifest = JSON.parse(read("plugins/demo/package.json"))
  manifest["agent-plugins"].shared = items
  put("plugins/demo/package.json", JSON.stringify(manifest))
}
const NOTE = "<!-- Generated by scripts/build.ts from shared/agents/challenger.md. Do not edit. -->"

describe("copying", () => {
  test("a listed file goes into every harness tree, with the header after the front matter", () => {
    put("shared/agents/challenger.md", AGENT)
    takes("agents/challenger")
    generate()
    for (const harness of ["opencode", "claude", "omp"]) {
      expect(read(`plugins/demo/${harness}/agents/challenger.md`)).toBe(
        `---\nname: challenger\ndescription: Argues the other side.\n---\n${NOTE}\nYou challenge claims.\n`,
      )
    }
    expect(stale()).toEqual([])
  })

  test("only listed items are copied", () => {
    put("shared/agents/challenger.md", AGENT)
    put("shared/agents/other.md", AGENT)
    put("shared/rules/unlisted.md", "# Unlisted\n")
    takes("agents/challenger")
    generate()
    expect(exists("plugins/demo/claude/agents/other.md")).toBe(false)
    expect(exists("plugins/demo/claude/rules/unlisted.md")).toBe(false)
  })

  test("a file without front matter gets the header on top, and OMP rules keep alwaysApply first", () => {
    put("shared/rules/plain.md", "# Plain\n")
    takes("rules/plain")
    generate()
    const note = "<!-- Generated by scripts/build.ts from shared/rules/plain.md. Do not edit. -->"
    expect(read("plugins/demo/claude/rules/plain.md")).toBe(`${note}\n\n# Plain\n`)
    expect(read("plugins/demo/omp/rules/plain.md")).toBe(`---\nalwaysApply: true\n---\n${note}\n\n# Plain\n`)
  })

  test("a directory item copies every file; only Markdown gets the header", () => {
    put("shared/skills/y/SKILL.md", "---\nname: y\ndescription: Shared.\n---\nBody\n")
    put("shared/skills/y/tool.json", '{"a":1}')
    takes("skills/y")
    generate()
    expect(read("plugins/demo/opencode/skills/y/SKILL.md")).toContain("Generated by scripts/build.ts from shared/skills/y/SKILL.md")
    expect(read("plugins/demo/opencode/skills/y/tool.json")).toBe('{"a":1}')
  })

  test("x.<harness>.md variants work in the shared directory", () => {
    put("shared/agents/challenger.md", AGENT)
    put("shared/agents/challenger.claude.md", "---\nname: challenger\n---\nClaude wording\n")
    takes("agents/challenger")
    generate()
    expect(read("plugins/demo/claude/agents/challenger.md")).toContain("Claude wording")
    expect(read("plugins/demo/opencode/agents/challenger.md")).toContain("You challenge claims.")
    expect(exists("plugins/demo/claude/agents/challenger.claude.md")).toBe(false)
  })

  test("two plugins that take the same item get the same text", () => {
    put("shared/agents/challenger.md", AGENT)
    takes("agents/challenger")
    const second = JSON.parse(read("plugins/demo/package.json"))
    second.name = "second"
    put("plugins/second/package.json", JSON.stringify(second))
    mkdirSync(path.join(root, "plugins/second/opencode"), { recursive: true })
    writeFileSync(path.join(root, "plugins/second/opencode/index.js"), "export default {}\n")
    for (const harness of ["claude", "omp"]) mkdirSync(path.join(root, `plugins/second/${harness}`), { recursive: true })
    generate()
    expect(read("plugins/second/claude/agents/challenger.md")).toBe(read("plugins/demo/claude/agents/challenger.md"))
  })

  test("the copy shows up in the inventory", () => {
    put("shared/agents/challenger.md", AGENT)
    takes("agents/challenger")
    generate()
    const entry = JSON.parse(read("inventory.json")).plugins[0]
    expect(entry.shared).toEqual(["agents/challenger"])
    expect(entry.harnesses.claude.agents).toEqual(["challenger"])
  })

  test("sharedDir names the directory", () => {
    config.sharedDir = "common-parts"
    put("common-parts/agents/challenger.md", AGENT)
    takes("agents/challenger")
    generate()
    expect(read("plugins/demo/claude/agents/challenger.md")).toContain("from common-parts/agents/challenger.md")
  })
})

describe("errors", () => {
  test("a missing item names the item and the directory", () => {
    takes("agents/ghost")
    expect(() => readPlugins(root, config)).toThrow(/shared item "agents\/ghost" not found in shared\/agents\//)
  })

  test("a file of the plugin's own at the same path is a clash", () => {
    put("shared/agents/challenger.md", AGENT)
    put("plugins/demo/common/agents/challenger.md", "own\n")
    takes("agents/challenger")
    expect(() => readPlugins(root, config)).toThrow(/clashes with its own common\/agents\/challenger\.md/)
  })

  test("an own variant of the same name is a clash too", () => {
    put("shared/agents/challenger.md", AGENT)
    put("plugins/demo/common/agents/challenger.claude.md", "own\n")
    takes("agents/challenger")
    expect(() => readPlugins(root, config)).toThrow(/clashes/)
  })

  test.each([
    ["an item outside commonDirs", ["widgets/x"], /not in commonDirs/],
    ["a bare name", ["challenger"], /relative path like "agents\/name"/],
    ["a parent path", ["agents/../x"], /relative path/],
    ["a duplicate", ["agents/a", "agents/a"], /twice/],
    ["an empty list", [], /non-empty list/],
  ])("rejects %s", (_label, items, message) => {
    takes(...(items as string[]))
    expect(() => readPlugins(root, config)).toThrow(message)
  })
})

describe("drift", () => {
  test("editing the shared file makes every consumer's copy stale", () => {
    put("shared/agents/challenger.md", AGENT)
    takes("agents/challenger")
    generate()
    put("shared/agents/challenger.md", AGENT.replace("challenge", "question"))
    expect(stale()).toEqual(["opencode", "claude", "omp"].map((h) => `plugins/demo/${h}/agents/challenger.md`).sort())
  })

  test("a hand-edited copy is stale", () => {
    put("shared/agents/challenger.md", AGENT)
    takes("agents/challenger")
    generate()
    put("plugins/demo/claude/agents/challenger.md", "edited\n")
    expect(stale()).toEqual(["plugins/demo/claude/agents/challenger.md"])
  })

  test("dropping the item removes the copies on build", () => {
    put("shared/agents/challenger.md", AGENT)
    takes("agents/challenger")
    generate()
    const manifest = JSON.parse(read("plugins/demo/package.json"))
    delete manifest["agent-plugins"].shared
    put("plugins/demo/package.json", JSON.stringify(manifest))
    expect(stale()).toContain("plugins/demo/claude/agents/challenger.md")
    generate()
    expect(exists("plugins/demo/claude/agents/challenger.md")).toBe(false)
    expect(exists("plugins/demo/claude/agents")).toBe(false)
  })

  test("a plugin without shared items is unaffected by the shared directory", () => {
    put("shared/agents/challenger.md", AGENT)
    generate()
    expect(exists("plugins/demo/claude/agents")).toBe(false)
    expect(stale()).toEqual([])
    rmSync(path.join(root, "shared"), { recursive: true })
    expect(stale()).toEqual([])
  })
})
