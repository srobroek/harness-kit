// Generates every derived file in the repository from plugins/<name>/package.json and
// plugins/<name>/common/, following the repo's harness-kit.json. The CLI lives in cli.ts; this
// module holds the logic so tests can drive it against a fixture tree.

import { chmodSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs"
import path from "node:path"
import { type Config, type Harness, KNOWN_HARNESSES, KNOWN_KINDS, type Kind } from "./config"
import { RUNTIME_DIR, type RuntimeModuleName, resolveRuntime, vendoredSource } from "./runtime"
import { fail, isRecord, json, nonEmptyString } from "./util"

export type { Harness, Kind }
export type HarnessInventory = Record<Kind, string[]>

/** A user-facing option. Every harness exposes it its own way; the default is a string. */
export type PluginOption = { description: string; default: string }

export type Plugin = {
  name: string
  version: string
  description: string
  category: string
  harnesses: Harness[]
  scope?: string
  /** One line on how the harness builds differ. */
  discrepancies?: string
  /** Options the plugin's templates take, by name. A name is letters, digits and underscores. Exclusive with `userConfig`. */
  options?: Record<string, PluginOption>
  /** Name of the Claude plugin when it differs from the directory name; it sets the `/<name>:<command>` namespace. */
  claudeName?: string
  /** Author and license go into the Claude manifest, which strict validation requires. */
  author?: { name: string }
  license?: string
  /** The Claude `userConfig` schema, copied into plugin.json as is. Exclusive with `options`. */
  userConfig?: Record<string, unknown>
  /** Items of the repo's shared directory this plugin takes, like `agents/x` or `skills/y`. Copied into every harness tree. */
  shared?: string[]
  /** Runtime modules vendored into the harness trees as `_kit/`, with their dependencies. Absent when the plugin opts out. */
  runtime?: RuntimeModuleName[]
}

/** `executable` is set on copies of source files: the output must carry the source's executable bit. Unset leaves the mode alone. */
export type Output = { file: string; contents: string | Buffer; executable?: boolean }
export type Drift = { changed: string[]; extra: string[] }

const NAME_PATTERN = /^[a-z0-9][a-z0-9-]*$/
const SEMVER = /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?$/
const SHARED_ITEM = /^[A-Za-z0-9._-]+(?:\/[A-Za-z0-9._-]+)+$/
const OPTION_NAME = /^[a-z][a-z0-9_]*$/
const OPENCODE_SDK_RANGE = ">=2.1.4 <3"
/** The owner-execute bit decides whether a file counts as executable; chmod keeps group and other in step with their read bits. */
const OWNER_EXEC = 0o100
const EXEC_BITS = 0o111
const MODULE_EXTENSION = /\.(?:[cm]?[jt]s)$/

const generatedNote = (config: Config) => `<!-- Generated by ${config.generatedBy}. Do not edit. -->`

export function assertSemver(version: string): void {
  if (!SEMVER.test(version)) throw new Error(`"${version}" is not a semver version (expected x.y.z)`)
}

function listDirs(dir: string): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
}

/** Files under dir as sorted posix-style paths relative to it. */
function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return []
  const found: string[] = []
  const walk = (current: string, prefix: string) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      // Bytecode caches that a test or a run leaves behind are not content.
      if (entry.name === "__pycache__") continue
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name
      if (entry.isDirectory()) walk(path.join(current, entry.name), relative)
      else found.push(relative)
    }
  }
  walk(dir, "")
  return found.sort()
}

const stripExtension = (file: string) => file.replace(/\.[^./]+$/, "")

export function readPlugin(root: string, name: string, config: Config): Plugin {
  const key = config.pluginKey
  const where = `plugins/${name}/package.json`
  const file = path.join(root, "plugins", name, "package.json")
  if (!existsSync(file)) fail(where, "missing")
  const manifest = JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>
  if (manifest.name !== name) fail(where, `name "${String(manifest.name)}" must equal the directory name "${name}"`)
  if (!NAME_PATTERN.test(name)) fail(where, `"${name}" is not a valid plugin name`)
  const version = manifest.version
  if (typeof version !== "string" || !SEMVER.test(version)) fail(where, `version "${String(version)}" is not semver`)
  const own = manifest[key]
  if (!isRecord(own)) fail(where, `missing "${key}" key`)
  const description = nonEmptyString(where, `${key}.description`, own.description)
  const category = nonEmptyString(where, `${key}.category`, own.category)
  const harnesses = own.harnesses
  if (!Array.isArray(harnesses) || harnesses.length === 0) fail(where, "harnesses must list at least one harness")
  for (const harness of harnesses) {
    if (!(KNOWN_HARNESSES as readonly unknown[]).includes(harness)) {
      fail(where, `unknown harness "${String(harness)}" (use ${KNOWN_HARNESSES.join(", ")})`)
    }
    if (!(config.harnesses as readonly unknown[]).includes(harness)) {
      fail(where, `harness "${String(harness)}" is not enabled in harness-kit.json (enabled: ${config.harnesses.join(", ")})`)
    }
  }
  const scope = own.scope === undefined ? undefined : nonEmptyString(where, `${key}.scope`, own.scope)
  for (const harness of KNOWN_HARNESSES) {
    if (!harnesses.includes(harness) && existsSync(path.join(root, "plugins", name, harness))) {
      fail(`plugins/${name}/${harness}`, `exists but "${harness}" is not in harnesses`)
    }
  }
  const discrepancies = own.discrepancies === undefined ? undefined : nonEmptyString(where, `${key}.discrepancies`, own.discrepancies)
  if (discrepancies !== undefined && /[\r\n]/.test(discrepancies)) fail(where, `"${key}.discrepancies" must be one line`)
  const options = readOptions(where, key, own.options)
  let claudeName: string | undefined
  if (own.claudeName !== undefined) {
    claudeName = nonEmptyString(where, `${key}.claudeName`, own.claudeName)
    if (!NAME_PATTERN.test(claudeName)) fail(where, `"${key}.claudeName" must be kebab-case`)
  }
  let author: { name: string } | undefined
  if (manifest.author !== undefined) {
    const raw = manifest.author
    const authorName = typeof raw === "string" ? raw : isRecord(raw) ? raw.name : undefined
    if (typeof authorName !== "string" || !authorName.trim()) fail(where, '"author" must be a string or an object with a name')
    author = { name: authorName }
  }
  const license = manifest.license === undefined ? undefined : nonEmptyString(where, "license", manifest.license)
  if (own.userConfig !== undefined && !isRecord(own.userConfig)) fail(where, `"${key}.userConfig" must be an object`)
  const userConfig = own.userConfig as Record<string, unknown> | undefined
  if (options && userConfig) fail(where, `set either "${key}.options" or "${key}.userConfig", not both: options generate the userConfig`)
  const selectedHarnesses = KNOWN_HARNESSES.filter((h) => harnesses.includes(h))
  const runtime = readRuntime(where, key, own.runtime, selectedHarnesses)
  const shared = readShared(where, key, own.shared, config)
  // Keep canonical harness order so output does not depend on how the author ordered the list.
  return {
    name,
    version,
    description,
    category,
    harnesses: selectedHarnesses,
    scope,
    discrepancies,
    options,
    claudeName,
    author,
    license,
    userConfig,
    shared,
    runtime,
  }
}

function readShared(where: string, key: string, raw: unknown, config: Config): string[] | undefined {
  if (raw === undefined) return undefined
  if (!Array.isArray(raw) || raw.length === 0) fail(where, `"${key}.shared" must be a non-empty list of items like "agents/name"`)
  for (const item of raw) {
    if (typeof item !== "string" || !SHARED_ITEM.test(item) || item.split("/").includes("..")) {
      fail(where, `"${key}.shared" item ${JSON.stringify(item)} must be a relative path like "agents/name"`)
    }
    const dir = item.split("/")[0]!
    if (!config.commonDirs.includes(dir)) fail(where, `shared item "${item}" is in "${dir}", which is not in commonDirs (${config.commonDirs.join(", ")})`)
  }
  if (new Set(raw).size !== raw.length) fail(where, `"${key}.shared" lists an item twice`)
  return raw as string[]
}

function readRuntime(where: string, key: string, raw: unknown, harnesses: Harness[]): RuntimeModuleName[] | undefined {
  if (raw === undefined || raw === false) return undefined
  const valid = raw === true || (Array.isArray(raw) && raw.length > 0 && raw.every((item) => typeof item === "string"))
  if (!valid) fail(where, `"${key}.runtime" must be true or a non-empty list of module names`)
  try {
    const modules = resolveRuntime(raw as boolean | string[], harnesses)
    return modules.length > 0 ? modules : undefined
  } catch (error) {
    return fail(where, `"${key}.runtime": ${error instanceof Error ? error.message : String(error)}`)
  }
}

function readOptions(where: string, key: string, raw: unknown): Record<string, PluginOption> | undefined {
  if (raw === undefined) return undefined
  if (!isRecord(raw)) fail(where, `"${key}.options" must be an object`)
  const options: Record<string, PluginOption> = {}
  for (const [name, value] of Object.entries(raw)) {
    if (!OPTION_NAME.test(name)) fail(where, `option "${name}" must be lowercase letters, digits and underscores`)
    if (!isRecord(value)) fail(where, `option "${name}" must be an object`)
    const description = nonEmptyString(where, `option "${name}" description`, value.description)
    if (typeof value.default !== "string") fail(where, `option "${name}" needs a string "default"`)
    options[name] = { description, default: value.default }
  }
  return options
}

/** Bare specifiers (neither relative nor `node:`) imported or re-exported by a module's source text. */
export function bareImports(source: string): string[] {
  const found: string[] = []
  const pattern = /(?:^|[;\n])\s*(?:(?:import|export)\b[^"'`;]*?\bfrom\s*|import\s*)["']([^"']+)["']/g
  for (const match of source.matchAll(pattern)) {
    const specifier = match[1] as string
    if (!specifier.startsWith(".") && !specifier.startsWith("/") && !specifier.startsWith("node:")) found.push(specifier)
  }
  return found
}

/**
 * OpenCode resolves host-provided packages (the plugin SDK, OpenTUI, Solid) only for modules reached through an import.
 * The files it loads first, the targets of the OpenCode package `exports`, must therefore import nothing bare.
 */
function checkOpencodeEntries(root: string, plugin: Plugin): void {
  if (!plugin.harnesses.includes("opencode")) return
  const dir = harnessDir(root, plugin, "opencode")
  for (const target of Object.values(opencodeExports(root, plugin))) {
    const file = path.join(dir, target)
    if (!existsSync(file)) continue
    const bare = bareImports(readFileSync(file, "utf8"))
    if (bare.length > 0) {
      fail(`plugins/${plugin.name}/opencode/${target.replace("./", "")}`, `entry file imports ${bare.map((x) => `"${x}"`).join(", ")} directly; move it behind a shim (the entry re-exports from another module)`)
    }
  }
}

export function readPlugins(root: string, config: Config): Plugin[] {
  const plugins = listDirs(path.join(root, "plugins")).map((name) => readPlugin(root, name, config))
  for (const plugin of plugins) {
    checkOpencodeEntries(root, plugin)
    resolveShared(root, plugin, config)
  }
  return plugins
}

const pluginDir = (root: string, plugin: Plugin) => path.join(root, "plugins", plugin.name)
const harnessDir = (root: string, plugin: Plugin, harness: Harness) => path.join(pluginDir(root, plugin), harness)

/** Matches `<name>.<harness>.<ext>`: a copy of `<name>.<ext>` that only that harness gets. */
const VARIANT = new RegExp(`^(.+)\\.(${KNOWN_HARNESSES.join("|")})(\\.[^./]+)$`)

/** OMP injects a plugin rule into the system prompt only when its front matter says `alwaysApply: true`. */
const OMP_ALWAYS_APPLY = "---\nalwaysApply: true\n---\n\n"

/**
 * The common files one harness receives, as [source, destination] pairs relative to common/<dir>.
 * `x.<harness>.md` replaces `x.md` in that harness and appears in no other.
 */
function commonFilesFor(files: string[], harness: Harness): Array<[string, string]> {
  const variantOf = (file: string) => {
    const match = VARIANT.exec(path.basename(file))
    return match ? { harness: match[2], plain: path.join(path.dirname(file), `${match[1]}${match[3]}`) } : undefined
  }
  const overridden = new Set(files.flatMap((file) => (variantOf(file)?.harness === harness ? [variantOf(file)!.plain] : [])))
  const picked: Array<[string, string]> = []
  for (const file of files) {
    const variant = variantOf(file)
    if (!variant) {
      if (!overridden.has(file)) picked.push([file, file])
    } else if (variant.harness === harness) picked.push([file, variant.plain])
  }
  return picked
}

/** The plain (variant-free) name of a file: `x.claude.md` and `x.md` both give `x.md`. */
function plainName(file: string): string {
  const match = VARIANT.exec(path.basename(file))
  return match ? path.join(path.dirname(file), `${match[1]}${match[3]}`) : file
}

/** Whether a file of the shared directory belongs to the item `rest` (the part after the kind directory). */
function belongsToItem(file: string, rest: string): boolean {
  if (file === rest || file.startsWith(`${rest}/`)) return true
  if (stripExtension(file) === rest) return true
  return stripExtension(plainName(file)) === rest
}

/** Shared files a plugin takes, by kind directory: paths relative to <sharedDir>/<dir>. Throws on a missing item or a clash. */
function resolveShared(root: string, plugin: Plugin, config: Config): Map<string, string[]> {
  const taken = new Map<string, string[]>()
  const common = path.join(pluginDir(root, plugin), "common")
  for (const item of plugin.shared ?? []) {
    const [dir, ...parts] = item.split("/") as [string, ...string[]]
    const rest = parts.join("/")
    const base = path.join(root, config.sharedDir, dir)
    const files = listFiles(base).filter((file) => belongsToItem(file, rest))
    if (files.length === 0) fail(`plugins/${plugin.name}/package.json`, `shared item "${item}" not found in ${config.sharedDir}/${dir}/`)
    const own = new Set(listFiles(path.join(common, dir)).map(plainName))
    for (const file of files) {
      if (own.has(plainName(file))) {
        fail(`plugins/${plugin.name}`, `shared item "${item}" clashes with its own common/${dir}/${plainName(file)}; remove one of them`)
      }
    }
    taken.set(dir, [...(taken.get(dir) ?? []), ...files])
  }
  return taken
}

/** Header for a copy of a shared Markdown file, placed after any front matter so the front matter still parses. */
function withSharedHeader(text: string, note: string): string {
  const front = /^---\r?\n[\s\S]*?\r?\n---\r?\n?/.exec(text)
  if (!front) return `${note}\n\n${text}`
  const head = front[0].endsWith("\n") ? front[0] : `${front[0]}\n`
  return `${head}${note}\n${text.slice(front[0].length)}`
}

function ownedCopies(root: string, plugin: Plugin, config: Config): Output[] {
  const common = path.join(pluginDir(root, plugin), "common")
  const shared = resolveShared(root, plugin, config)
  const outputs: Output[] = []
  for (const harness of plugin.harnesses) {
    for (const dir of config.commonDirs) {
      const own = listFiles(path.join(common, dir))
      const taken = shared.get(dir) ?? []
      for (const [source, dest] of commonFilesFor([...own, ...taken].sort(), harness)) {
        const isShared = taken.includes(source)
        const origin = isShared ? path.join(root, config.sharedDir, dir, source) : path.join(common, dir, source)
        let contents: string | Buffer = readFileSync(origin)
        if (harness === "omp" && dir === "rules" && !contents.subarray(0, 3).equals(Buffer.from("---"))) {
          contents = OMP_ALWAYS_APPLY + contents.toString("utf8")
        }
        if (isShared && source.endsWith(".md")) {
          const note = `<!-- Generated by ${config.generatedBy} from ${config.sharedDir}/${dir}/${source}. Do not edit. -->`
          contents = withSharedHeader(contents.toString("utf8"), note)
        }
        outputs.push({
          file: path.join(harnessDir(root, plugin, harness), dir, dest),
          contents,
          executable: (statSync(origin).mode & OWNER_EXEC) !== 0,
        })
      }
    }
  }
  return outputs
}

/** The opted-in runtime modules, copied into each harness tree's `_kit/` directory. */
function runtimeCopies(root: string, plugin: Plugin, config: Config): Output[] {
  return (plugin.runtime ?? []).map((name) => {
    const { harness, file, contents } = vendoredSource(name, config.generatedBy)
    return { file: path.join(harnessDir(root, plugin, harness), RUNTIME_DIR, file), contents }
  })
}

function ompExtensions(root: string, plugin: Plugin): string[] {
  const dir = path.join(harnessDir(root, plugin, "omp"), "extensions")
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && MODULE_EXTENSION.test(entry.name))
    .map((entry) => `./extensions/${entry.name}`)
    .sort()
}

function opencodeFile(root: string, plugin: Plugin, base: "index" | "tui"): string | undefined {
  const dir = harnessDir(root, plugin, "opencode")
  return [`${base}.ts`, `${base}.js`].find((file) => existsSync(path.join(dir, file)))
}

/** The `exports` map of the OpenCode package: the server entry, plus `./tui` when the tree has a TUI half. */
function opencodeExports(root: string, plugin: Plugin): Record<string, string> {
  const tui = opencodeFile(root, plugin, "tui")
  return { ".": `./${opencodeFile(root, plugin, "index") ?? "index.js"}`, ...(tui ? { "./tui": `./${tui}` } : {}) }
}

function claudeUserConfig(options: Record<string, PluginOption>) {
  return Object.fromEntries(
    Object.entries(options).map(([name, option]) => [
      name,
      { type: "string", title: name, description: option.description, default: option.default },
    ]),
  )
}

/** The defaults of the plugin's options, read at run time by every harness build. */
function optionDefaults(root: string, plugin: Plugin): Output[] {
  if (!plugin.options) return []
  const defaults = Object.fromEntries(Object.entries(plugin.options).map(([name, option]) => [name, option.default]))
  return plugin.harnesses.map((harness) => ({ file: path.join(harnessDir(root, plugin, harness), "options.json"), contents: json(defaults) }))
}

function manifests(root: string, plugin: Plugin, config: Config): Output[] {
  const { name, version, description, category } = plugin
  const outputs: Output[] = []
  const at = (harness: Harness, file: string) => path.join(harnessDir(root, plugin, harness), file)
  if (plugin.harnesses.includes("claude")) {
    const author = plugin.author ?? config.claude.author
    const license = plugin.license ?? config.claude.license
    const userConfig = plugin.userConfig ?? (plugin.options ? claudeUserConfig(plugin.options) : undefined)
    outputs.push({
      file: at("claude", ".claude-plugin/plugin.json"),
      contents: json({
        name: plugin.claudeName ?? name,
        description,
        version,
        ...(author ? { author } : {}),
        ...(license ? { license } : {}),
        ...(userConfig ? { userConfig } : {}),
      }),
    })
  }
  if (plugin.harnesses.includes("omp")) {
    outputs.push({
      file: at("omp", "package.json"),
      contents: json({
        name: `${config.ompScope}/${name}`,
        version,
        description,
        private: true,
        ...(config.omp.packageType ? { type: config.omp.packageType } : {}),
        omp: ompExtensions(root, plugin).length > 0 ? { extensions: ompExtensions(root, plugin) } : {},
      }),
    })
    outputs.push({ file: at("omp", ".omp-plugin/plugin.json"), contents: json({ name, description, version, category }) })
  }
  if (plugin.harnesses.includes("opencode")) {
    outputs.push({
      file: at("opencode", "package.json"),
      contents: json({
        name: `${name}-opencode`,
        version,
        private: true,
        type: "module",
        exports: opencodeExports(root, plugin),
        peerDependencies: { "@opencode/plugin": OPENCODE_SDK_RANGE },
        peerDependenciesMeta: { "@opencode/plugin": { optional: true } },
      }),
    })
  }
  return outputs
}

function readJsonFile(file: string): unknown {
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : undefined
}

/** What one harness tree ships. `generated` holds the paths (relative to the tree) this run copies in. */
function inventoryOf(root: string, plugin: Plugin, harness: Harness, generated: string[], config: Config): HarnessInventory {
  const dir = harnessDir(root, plugin, harness)
  const own = listFiles(dir).filter((file) => !config.commonDirs.some((common) => file.startsWith(`${common}/`)))
  const files = [...new Set([...own, ...generated])].sort()
  const names = (prefix: string, accept: (rest: string) => boolean = () => true) =>
    files
      .filter((file) => file.startsWith(`${prefix}/`) && accept(file.slice(prefix.length + 1)))
      .map((file) => file.slice(prefix.length + 1))

  const skills = names("skills", (rest) => rest.endsWith("/SKILL.md")).map((rest) => rest.split("/")[0]!)
  const agents = names("agents", (rest) => rest.endsWith(".md") && !rest.includes("/")).map(stripExtension)
  const commands = names("commands", (rest) => rest.endsWith(".md")).map(stripExtension)
  const rules = names("rules", (rest) => /\.mdc?$/.test(rest)).map(stripExtension)
  const templates = names("templates", (rest) => /\.md$/.test(rest)).map(stripExtension)
  const styles = harness === "claude" ? names("output-styles", (rest) => rest.endsWith(".md") && !rest.includes("/")).map(stripExtension) : []

  const hooks: string[] = []
  if (harness === "claude") {
    const hooksConfig = readJsonFile(path.join(dir, "hooks", "hooks.json"))
    const events = isRecord(hooksConfig) && isRecord(hooksConfig.hooks) ? Object.keys(hooksConfig.hooks) : []
    hooks.push(...events)
  }
  if (harness === "omp") {
    for (const phase of ["pre", "post"]) hooks.push(...names(`hooks/${phase}`).map((rest) => `${phase}/${stripExtension(rest)}`))
  }

  const tools = names("tools").map((rest) => stripExtension(rest.split("/")[0]!))
  const extensions =
    harness === "opencode"
      ? files.filter((file) => /^(?:index|tui)\.[cm]?[jt]s$/.test(file)).map(stripExtension)
      : harness === "omp"
        ? names("extensions", (rest) => MODULE_EXTENSION.test(rest) && !rest.includes("/")).map(stripExtension)
        : []

  const mcpConfig = readJsonFile(path.join(dir, ".mcp.json"))
  const mcp = isRecord(mcpConfig) ? Object.keys(isRecord(mcpConfig.mcpServers) ? mcpConfig.mcpServers : mcpConfig) : []

  const unique = (list: string[]) => [...new Set(list)].sort()
  const found: HarnessInventory = {
    skills: unique(skills),
    agents: unique(agents),
    commands: unique(commands),
    rules: unique(rules),
    templates: unique(templates),
    styles: unique(styles),
    hooks: unique(hooks),
    tools: unique(tools),
    extensions: unique(extensions),
    mcp: unique(mcp),
  }
  // Only the kinds the repo enables appear, in canonical order.
  return Object.fromEntries(KNOWN_KINDS.filter((kind) => config.kinds.includes(kind)).map((kind) => [kind, found[kind]])) as HarnessInventory
}

type PluginInventory = Plugin & { harnesses: Harness[]; contents: Partial<Record<Harness, HarnessInventory>> }

function buildInventory(root: string, plugin: Plugin, copies: Output[], config: Config): PluginInventory {
  const contents: Partial<Record<Harness, HarnessInventory>> = {}
  for (const harness of plugin.harnesses) {
    const prefix = harnessDir(root, plugin, harness) + path.sep
    const generated = copies
      .filter((copy) => copy.file.startsWith(prefix))
      .map((copy) => copy.file.slice(prefix.length).split(path.sep).join("/"))
    contents[harness] = inventoryOf(root, plugin, harness, generated, config)
  }
  return { ...plugin, contents }
}

const cell = (names: string[]) => (names.length > 0 ? names.join(", ") : "-")

function pluginInventoryMarkdown(entry: PluginInventory, config: Config): string {
  const header = `| Kind | ${entry.harnesses.join(" | ")} |`
  const divider = `| --- |${entry.harnesses.map(() => " --- |").join("")}`
  const rows = config.kinds.map((kind) => `| ${kind} | ${entry.harnesses.map((h) => cell(entry.contents[h]![kind])).join(" | ")} |`)
  return [generatedNote(config), `# ${entry.name}`, "", entry.description, "", header, divider, ...rows, ""].join("\n")
}

function rootInventoryMarkdown(entries: PluginInventory[], config: Config): string {
  const lines = [generatedNote(config), "# Inventory", ""]
  if (entries.length === 0) {
    lines.push("No plugins yet.", "")
    return lines.join("\n")
  }
  lines.push("| Plugin | Version | Category | Scope | Harnesses |", "| --- | --- | --- | --- | --- |")
  for (const entry of entries) {
    lines.push(`| ${entry.name} | ${entry.version} | ${entry.category} | ${entry.scope ?? "-"} | ${entry.harnesses.join(", ")} |`)
  }
  lines.push("", "Each plugin's own `INVENTORY.md` lists what it ships per harness.", "")
  const notes = entries.filter((entry) => entry.discrepancies)
  if (notes.length > 0) {
    lines.push("## Harness discrepancies", "")
    for (const entry of notes) lines.push(`- ${entry.name}: ${entry.discrepancies}`)
    lines.push("")
  }
  return lines.join("\n")
}

/** Harnesses that read a marketplace file, with the directory that holds it. */
const MARKETPLACE_DIRS = { claude: ".claude-plugin", omp: ".omp-plugin" } as const

function marketplace(plugins: Plugin[], harness: keyof typeof MARKETPLACE_DIRS, config: Config) {
  return {
    $schema: "https://anthropic.com/claude-code/marketplace.schema.json",
    name: config.marketplace.name,
    owner: config.marketplace.owner,
    metadata: { description: config.marketplace.description },
    plugins: plugins
      .filter((plugin) => plugin.harnesses.includes(harness))
      .map((plugin) => ({
        name: harness === "claude" ? (plugin.claudeName ?? plugin.name) : plugin.name,
        description: plugin.description,
        source: `./plugins/${plugin.name}/${harness}`,
        version: plugin.version,
        category: plugin.category,
      })),
  }
}

/** Every generated file for the given plugins. */
export function render(root: string, plugins: Plugin[], config: Config): Output[] {
  const outputs: Output[] = (Object.keys(MARKETPLACE_DIRS) as Array<keyof typeof MARKETPLACE_DIRS>)
    .filter((harness) => config.harnesses.includes(harness))
    .map((harness) => ({
      file: path.join(root, MARKETPLACE_DIRS[harness], "marketplace.json"),
      contents: json(marketplace(plugins, harness, config)),
    }))
  const entries: PluginInventory[] = []
  for (const plugin of plugins) {
    const copies = [...ownedCopies(root, plugin, config), ...runtimeCopies(root, plugin, config)]
    const entry = buildInventory(root, plugin, copies, config)
    entries.push(entry)
    outputs.push(...manifests(root, plugin, config), ...optionDefaults(root, plugin), ...copies)
    outputs.push({ file: path.join(pluginDir(root, plugin), "INVENTORY.md"), contents: pluginInventoryMarkdown(entry, config) })
  }
  outputs.push({ file: path.join(root, "INVENTORY.md"), contents: rootInventoryMarkdown(entries, config) })
  outputs.push({
    file: path.join(root, "inventory.json"),
    contents: json({
      plugins: entries.map(({ contents, author, license, userConfig, ...plugin }) => ({ ...plugin, harnesses: contents })),
    }),
  })
  return outputs
}

/** Files in common-owned directories of a listed harness tree. Any not in a fresh render is stale. */
function ownedFiles(root: string, plugins: Plugin[], config: Config): string[] {
  return plugins.flatMap((plugin) =>
    plugin.harnesses.flatMap((harness) =>
      [...config.commonDirs, RUNTIME_DIR].flatMap((dir) => {
        const base = path.join(harnessDir(root, plugin, harness), dir)
        return listFiles(base).map((file) => path.join(base, file))
      }),
    ),
  )
}

function isExecutable(file: string): boolean {
  return (statSync(file).mode & OWNER_EXEC) !== 0
}

export function drift(root: string, outputs: readonly Output[], config: Config): Drift {
  const expected = new Set(outputs.map((output) => output.file))
  const changed = outputs
    .filter((output) => {
      if (!existsSync(output.file)) return true
      if (output.executable !== undefined && isExecutable(output.file) !== output.executable) return true
      return !Buffer.from(output.contents).equals(readFileSync(output.file))
    })
    .map((output) => output.file)
  const extra = ownedFiles(root, readPlugins(root, config), config).filter((file) => !expected.has(file))
  return { changed, extra }
}

export function write(root: string, outputs: readonly Output[], config: Config): void {
  for (const file of drift(root, outputs, config).extra) {
    rmSync(file)
    for (let dir = path.dirname(file); readdirSync(dir).length === 0; dir = path.dirname(dir)) rmSync(dir, { recursive: true })
  }
  for (const output of outputs) {
    mkdirSync(path.dirname(output.file), { recursive: true })
    writeFileSync(output.file, output.contents)
    if (output.executable !== undefined && isExecutable(output.file) !== output.executable) {
      const mode = statSync(output.file).mode & 0o777
      chmodSync(output.file, output.executable ? mode | OWNER_EXEC | ((mode & 0o444) >> 2) : mode & ~EXEC_BITS)
    }
  }
}

/** Set a plugin's version in package.json, then regenerate everything derived from it. */
export function stampVersion(root: string, name: string, version: string, config: Config): void {
  assertSemver(version)
  const plugins = readPlugins(root, config)
  if (!plugins.some((plugin) => plugin.name === name)) throw new Error(`unknown plugin "${name}"`)
  const file = path.join(root, "plugins", name, "package.json")
  const manifest = JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>
  manifest.version = version
  writeFileSync(file, json(manifest))
  const fresh = readPlugins(root, config)
  write(root, render(root, fresh, config), config)
}
