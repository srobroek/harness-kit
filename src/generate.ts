const MCP_SCHEMA = "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json"

/** The common MCP source is a shared, per-plugin declaration, separate from commonDirs. */
function commonMcpServers(root: string, plugin: Plugin): McpServers | undefined {
  const file = path.join(pluginDir(root, plugin), "common", ".mcp.json")
  if (!existsSync(file)) return undefined
  let raw: unknown
  try {
    raw = JSON.parse(readFileSync(file, "utf8"))
  } catch (error) {
    fail(`plugins/${plugin.name}/common/.mcp.json`, `is not valid JSON (${error instanceof Error ? error.message : String(error)})`)
  }
  if (!isRecord(raw) || !isRecord(raw.mcpServers)) fail(`plugins/${plugin.name}/common/.mcp.json`, 'must contain an "mcpServers" object')
  const servers: McpServers = {}
  for (const [name, value] of Object.entries(raw.mcpServers)) {
    if (!isRecord(value)) fail(`plugins/${plugin.name}/common/.mcp.json`, `"mcpServers.${name}" must be an object`)
    if (value.requiredEnv !== undefined && (!Array.isArray(value.requiredEnv) || value.requiredEnv.some((key) => typeof key !== "string" || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)))) fail(`plugins/${plugin.name}/common/.mcp.json`, `"mcpServers.${name}.requiredEnv" must be an array of environment variable names`)
    if (value.optionalHeaders !== undefined && (!isRecord(value.optionalHeaders) || Object.entries(value.optionalHeaders).some(([header, key]) => !header || typeof key !== "string" || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)))) fail(`plugins/${plugin.name}/common/.mcp.json`, `"mcpServers.${name}.optionalHeaders" must map HTTP header names to environment variable names`)
    if (value.enabled !== undefined && typeof value.enabled !== "boolean") fail(`plugins/${plugin.name}/common/.mcp.json`, `"mcpServers.${name}.enabled" must be true or false`)
    servers[name] = value
  }
  return servers
}

function ompMcpOutputs(root: string, plugin: Plugin, servers: McpServers): Output[] {
  return [{
    file: path.join(harnessDir(root, plugin, "omp"), "mcp.json"),
    contents: json({ $schema: MCP_SCHEMA, mcpServers: mcpServersForOmp(servers, plugin.name) }),
  }]
}

function mcpOutputs(root: string, plugin: Plugin): Output[] {
  const servers = commonMcpServers(root, plugin)
  if (!servers) return []
  const outputs: Output[] = []
  if (plugin.harnesses.includes("omp")) outputs.push(...ompMcpOutputs(root, plugin, servers))
  if (plugin.harnesses.includes("claude")) outputs.push({
    file: path.join(harnessDir(root, plugin, "claude"), ".mcp.json"),
    contents: json({ $schema: MCP_SCHEMA, mcpServers: mcpServersForClaude(servers) }),
  })
  if (plugin.harnesses.includes("pi")) outputs.push({ file: path.join(harnessDir(root, plugin, "pi"), "mcp-servers.ts"), contents: piMcpExtension(servers) })
  return outputs
}

function manifests(root: string, plugin: Plugin, config: Config, copies: readonly Output[], publish?: PublishSettings): Output[] {
  const { name, version, description, category } = plugin
  const outputs: Output[] = []
  const at = (harness: Harness, file: string) => path.join(harnessDir(root, plugin, harness), file)
  const ompEntries = plugin.harnesses.includes("omp") ? [...ompExtensions(root, plugin), ...prereqsEntry(generatedIn(root, plugin, "omp", copies))] : []
  if (plugin.harnesses.includes("claude")) {
    const author = plugin.author ?? config.claude.author
    const { homepage, repository } = claudeLinks(plugin, config)
    const license = plugin.license ?? config.claude.license
    const userConfig = plugin.userConfig ?? (plugin.options ? claudeUserConfig(plugin.options) : undefined)
    outputs.push({
      file: at("claude", ".claude-plugin/plugin.json"),
      contents: json({
        name: plugin.claudeName ?? name,
        description,
        version,
        ...(author ? { author } : {}),
        ...(homepage ? { homepage } : {}),
        ...(repository ? { repository } : {}),
        ...(license ? { license } : {}),
        ...(userConfig ? { userConfig } : {}),
        ...(plugin.claude?.dependencies ? { dependencies: plugin.claude.dependencies } : {}),
      }),
    })
  }
  if (plugin.harnesses.includes("omp")) {
    outputs.push({
      file: at("omp", "package.json"),
      contents: json({
        name: `${config.ompScope}/${name}`,
        version,
        description,
        private: true,
        ...(config.omp.packageType ? { type: config.omp.packageType } : {}),
        omp: ompEntries.length > 0 ? { extensions: ompEntries } : {},
      }),
    })
    outputs.push({ file: at("omp", ".omp-plugin/plugin.json"), contents: json({ name, description, version, category }) })
  }
  if (plugin.harnesses.includes("opencode")) {
    outputs.push({
      file: at("opencode", "package.json"),
      contents: json({
        name: `${name}-opencode`,
        version,
        private: true,
        type: "module",
        exports: opencodeExports(root, plugin),
        peerDependencies: { "@opencode/plugin": OPENCODE_SDK_RANGE },
        peerDependenciesMeta: { "@opencode/plugin": { optional: true } },
      }),
    })
  }
  if (plugin.harnesses.includes("pi")) {
    const files = treeFiles(root, plugin, "pi", generatedIn(root, plugin, "pi", copies), config)
    const npm = publish ? publishFields(root, plugin, publish, files, ownFiles(root, plugin, "pi", config)) : {}
    outputs.push({
      file: at("pi", "package.json"),
      contents: json({ name: piPackageName(plugin, config), version, description, keywords: ["pi-package"], ...npm, pi: piResources(files) }),
    })
  }
  return outputs
}

function readJsonFile(file: string): unknown {
  return existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : undefined
}

/** What one harness tree ships. `generated` holds the paths (relative to the tree) this run copies in. */
function inventoryOf(root: string, plugin: Plugin, harness: Harness, generated: string[], config: Config): HarnessInventory {
  const dir = harnessDir(root, plugin, harness)
  const files = treeFiles(root, plugin, harness, generated, config)
  const names = (prefix: string, accept: (rest: string) => boolean = () => true) =>
    files
      .filter((file) => file.startsWith(`${prefix}/`) && accept(file.slice(prefix.length + 1)))
      .map((file) => file.slice(prefix.length + 1))

  const skills = names("skills", (rest) => rest.endsWith("/SKILL.md")).map((rest) => rest.split("/")[0]!)
  const agents = names("agents", (rest) => rest.endsWith(".md") && !rest.includes("/")).map(stripExtension)
  const commands = names("commands", (rest) => rest.endsWith(".md")).map(stripExtension)
  const rules = names("rules", (rest) => /\.mdc?$/.test(rest)).map(stripExtension)
  const templates = names("templates", (rest) => /\.md$/.test(rest)).map(stripExtension)
  const styles = harness === "claude" ? names("output-styles", (rest) => rest.endsWith(".md") && !rest.includes("/")).map(stripExtension) : []

  const hooks: string[] = []
  if (harness === "claude") {
    const hooksConfig = readJsonFile(path.join(dir, "hooks", "hooks.json"))
    const events = isRecord(hooksConfig) && isRecord(hooksConfig.hooks) ? Object.keys(hooksConfig.hooks) : []
    hooks.push(...events)
  }
  if (harness === "omp") {
    for (const phase of ["pre", "post"]) hooks.push(...names(`hooks/${phase}`).map((rest) => `${phase}/${stripExtension(rest)}`))
  }

  const tools = names("tools").map((rest) => stripExtension(rest.split("/")[0]!))
  const extensions =
    harness === "opencode"
      ? files.filter((file) => /^(?:index|tui)\.[cm]?[jt]s$/.test(file)).map(stripExtension)
      : harness === "omp" || harness === "pi"
        ? names("extensions", (rest) => MODULE_EXTENSION.test(rest) && !rest.includes("/")).map(stripExtension)
        : []

  const pluginMcp = commonMcpServers(root, plugin)
  const mcpConfig = harness === "claude" && pluginMcp !== undefined ? undefined : readJsonFile(path.join(dir, ".mcp.json"))
  const mcp = isRecord(mcpConfig) ? Object.keys(isRecord(mcpConfig.mcpServers) ? mcpConfig.mcpServers : mcpConfig) : []
  if (harness === "omp") {
    const existing = pluginMcp === undefined ? readJsonFile(path.join(dir, "mcp.json")) : undefined
    if (isRecord(existing) && isRecord(existing.mcpServers)) mcp.push(...Object.keys(existing.mcpServers))
    if (pluginMcp !== undefined) mcp.push(...Object.keys(mcpServersForOmp(pluginMcp, plugin.name)))
  }
  if (harness === "claude" && pluginMcp !== undefined) mcp.push(...Object.keys(mcpServersForClaude(pluginMcp)))
  if (harness === "pi" && files.includes("mcp-servers.ts") && pluginMcp) mcp.push(...Object.keys(Object.fromEntries(Object.entries(pluginMcp).filter(([, server]) => server.enabled !== false))))
  const unique = (list: string[]) => [...new Set(list)].sort()
  const found: HarnessInventory = {
    skills: unique(skills),
    agents: unique(agents),
    commands: unique(commands),
    rules: unique(rules),
    templates: unique(templates),
    styles: unique(styles),
    hooks: unique(hooks),
    tools: unique(tools),
    extensions: unique(extensions),
    mcp: unique(mcp),
  }
  // Only the kinds the repo enables appear, in canonical order.
  return Object.fromEntries(KNOWN_KINDS.filter((kind) => config.kinds.includes(kind)).map((kind) => [kind, found[kind]])) as HarnessInventory
}

type PluginInventory = Plugin & { harnesses: Harness[]; contents: Partial<Record<Harness, HarnessInventory>> }

function buildInventory(root: string, plugin: Plugin, copies: Output[], config: Config): PluginInventory {
  const contents: Partial<Record<Harness, HarnessInventory>> = {}
  for (const harness of plugin.harnesses) contents[harness] = inventoryOf(root, plugin, harness, generatedIn(root, plugin, harness, copies), config)
  return { ...plugin, contents }
}

const cell = (names: string[]) => (names.length > 0 ? names.join(", ") : "-")
const tableText = (text: string) => text.replaceAll("|", "\\|")

/** The plugin's prerequisites as a Markdown section; empty when it declares none. Every harness needs them, so they have no column. */
function prerequisitesMarkdown(prerequisites: readonly Prerequisite[] | undefined): string[] {
  if (!prerequisites) return []
  const rows = prerequisites.map((item) =>
    [item.bin, item.required ? "yes" : "no", item.version ?? "any", item.for, installHint(item.install)].map(tableText).join(" | "),
  )
  return ["", "## Prerequisites", "", "| Tool | Required | Version | For | Install |", "| --- | --- | --- | --- | --- |", ...rows.map((row) => `| ${row} |`)]
}

function pluginInventoryMarkdown(entry: PluginInventory, config: Config): string {
  const header = `| Kind | ${entry.harnesses.join(" | ")} |`
  const divider = `| --- |${entry.harnesses.map(() => " --- |").join("")}`
  const rows = config.kinds.map((kind) => `| ${kind} | ${entry.harnesses.map((h) => cell(entry.contents[h]![kind])).join(" | ")} |`)
  return [generatedNote(config), `# ${entry.name}`, "", entry.description, "", header, divider, ...rows, ...prerequisitesMarkdown(entry.prerequisites), ""].join("\n")
}

function rootInventoryMarkdown(entries: PluginInventory[], config: Config): string {
  const lines = [generatedNote(config), "# Inventory", ""]
  if (entries.length === 0) {
    lines.push("No plugins yet.", "")
    return lines.join("\n")
  }
  lines.push("| Plugin | Version | Category | Scope | Harnesses |", "| --- | --- | --- | --- | --- |")
  for (const entry of entries) {
    lines.push(`| ${entry.name} | ${entry.version} | ${entry.category} | ${entry.scope ?? "-"} | ${entry.harnesses.join(", ")} |`)
  }
  lines.push("", "Each plugin's own `INVENTORY.md` lists what it ships per harness.", "")
  const notes = entries.filter((entry) => entry.discrepancies)
  if (notes.length > 0) {
    lines.push("## Harness discrepancies", "")
    for (const entry of notes) lines.push(`- ${entry.name}: ${entry.discrepancies}`)
    lines.push("")
  }
  return lines.join("\n")
}

/** Harnesses that read a marketplace file, with the directory that holds it. */
const MARKETPLACE_DIRS = { claude: ".claude-plugin", omp: ".omp-plugin" } as const

function marketplace(plugins: Plugin[], harness: keyof typeof MARKETPLACE_DIRS, config: Config) {
  return {
    $schema: "https://anthropic.com/claude-code/marketplace.schema.json",
    name: config.marketplace.name,
    owner: config.marketplace.owner,
    metadata: { description: config.marketplace.description },
    plugins: plugins
      .filter((plugin) => plugin.harnesses.includes(harness))
      .map((plugin) => {
        const { homepage, repository } = harness === "claude" ? claudeLinks(plugin, config) : {}
        return {
          name: harness === "claude" ? (plugin.claudeName ?? plugin.name) : plugin.name,
          description: plugin.description,
          source: `./plugins/${plugin.name}/${harness}`,
          version: plugin.version,
          category: plugin.category,
          ...(homepage ? { homepage } : {}),
          ...(repository ? { repository } : {}),
        }
      }),
  }
}

/** Every generated file for the given plugins. */
export function render(root: string, plugins: Plugin[], config: Config): Output[] {
  const outputs: Output[] = (Object.keys(MARKETPLACE_DIRS) as Array<keyof typeof MARKETPLACE_DIRS>)
    .filter((harness) => config.harnesses.includes(harness))
    .map((harness) => ({
      file: path.join(root, MARKETPLACE_DIRS[harness], "marketplace.json"),
      contents: json(marketplace(plugins, harness, config)),
    }))
  const entries: PluginInventory[] = []
  const publish = config.pi.publish && plugins.some((plugin) => plugin.harnesses.includes("pi")) ? readPublishSettings(root) : undefined
  for (const plugin of plugins) {
    // options.json counts as a copy, so a published tree's `files` list names it on the first build too.
    const copies = [...ownedCopies(root, plugin, config), ...runtimeCopies(root, plugin, config), ...piRootCopies(root, plugin, config), ...optionDefaults(root, plugin), ...mcpOutputs(root, plugin)]
    copies.push(...piRulesLoader(root, plugin, copies, config), ...prerequisiteFiles(root, plugin, config))
    const entry = buildInventory(root, plugin, copies, config)
    entries.push(entry)
    outputs.push(...manifests(root, plugin, config, copies, publish), ...copies)
    outputs.push({ file: path.join(pluginDir(root, plugin), "INVENTORY.md"), contents: pluginInventoryMarkdown(entry, config) })
  }
  outputs.push({ file: path.join(root, "INVENTORY.md"), contents: rootInventoryMarkdown(entries, config) })
  outputs.push({
    file: path.join(root, "inventory.json"),
    contents: json({
      plugins: entries.map(({ contents, author, license, userConfig, claude, ...plugin }) => ({ ...plugin, harnesses: contents })),
    }),
  })
  return outputs
}

/** Files in the directories and root files the build owns in a listed harness tree. Any not in a fresh render is stale. */
function ownedFiles(root: string, plugins: Plugin[], config: Config): string[] {
  return plugins.flatMap((plugin) =>
    plugin.harnesses.flatMap((harness) => {
      const tree = harnessDir(root, plugin, harness)
      const isMcpOutput = (file: string) => {
        if (harness === "pi" && file === "mcp-servers.ts") return existsSync(path.join(tree, file)) && readFileSync(path.join(tree, file), "utf8").startsWith("// Generated by harness-kit.")
        if ((harness === "omp" && file === "mcp.json") || (harness === "claude" && file === ".mcp.json")) {
          try {
            const output = readJsonFile(path.join(tree, file))
            return isRecord(output) && output.$schema === MCP_SCHEMA
          } catch {
            return false
          }
        }
        return false
      }
      const inDirs = [...config.commonDirs, RUNTIME_DIR, "mcp-servers"].flatMap((dir) => listFiles(path.join(tree, dir)).filter((file) => dir !== "mcp-servers" || isMcpOutput(file)).map((file) => path.join(tree, dir, file)))
      const atRoot = [...ownedRootFiles(plugin, harness, config), ...listFiles(tree).filter(isMcpOutput)].map((file) => path.join(tree, file)).filter((file) => existsSync(file))
      return [...inDirs, ...atRoot]
    }),
  )
}

function isExecutable(file: string): boolean {
  return (statSync(file).mode & OWNER_EXEC) !== 0
}

export function drift(root: string, outputs: readonly Output[], config: Config): Drift {
  const expected = new Set(outputs.map((output) => output.file))
  const changed = outputs
    .filter((output) => {
      if (!existsSync(output.file)) return true
      if (output.executable !== undefined && isExecutable(output.file) !== output.executable) return true
      return !Buffer.from(output.contents).equals(readFileSync(output.file))
    })
    .map((output) => output.file)
  const extra = ownedFiles(root, readPlugins(root, config), config).filter((file) => !expected.has(file))
  return { changed, extra }
}

export function write(root: string, outputs: readonly Output[], config: Config): void {
  for (const file of drift(root, outputs, config).extra) {
    rmSync(file)
    for (let dir = path.dirname(file); readdirSync(dir).length === 0; dir = path.dirname(dir)) rmSync(dir, { recursive: true })
  }
  for (const output of outputs) {
    mkdirSync(path.dirname(output.file), { recursive: true })
    writeFileSync(output.file, output.contents)
    if (output.executable !== undefined && isExecutable(output.file) !== output.executable) {
      const mode = statSync(output.file).mode & 0o777
      chmodSync(output.file, output.executable ? mode | OWNER_EXEC | ((mode & 0o444) >> 2) : mode & ~EXEC_BITS)
    }
  }
}

/** Set a plugin's version in package.json, then regenerate everything derived from it. */
export function stampVersion(root: string, name: string, version: string, config: Config): void {
  assertSemver(version)
  const plugins = readPlugins(root, config)
  if (!plugins.some((plugin) => plugin.name === name)) throw new Error(`unknown plugin "${name}"`)
  const file = path.join(root, "plugins", name, "package.json")
  const manifest = JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>
  manifest.version = version
  writeFileSync(file, json(manifest))
  const fresh = readPlugins(root, config)
  write(root, render(root, fresh, config), config)
}
