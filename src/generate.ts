export function assertSemver(version: string): void {
  if (!SEMVER.test(version)) throw new Error(`"${version}" is not a semver version (expected x.y.z)`)
}

function listDirs(dir: string): string[] {
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
}

/** Files under dir as sorted posix-style paths relative to it. */
function listFiles(dir: string): string[] {
  if (!existsSync(dir)) return []
  const found: string[] = []
  const walk = (current: string, prefix: string) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      // Bytecode caches that a test or a run leaves behind are not content.
      if (entry.name === "__pycache__") continue
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name
      if (entry.isDirectory()) walk(path.join(current, entry.name), relative)
      else found.push(relative)
    }
  }
  walk(dir, "")
  return found.sort()
}

const stripExtension = (file: string) => file.replace(/\.[^./]+$/, "")

export function readPlugin(root: string, name: string, config: Config): Plugin {
  const key = config.pluginKey
  const where = `plugins/${name}/package.json`
  const file = path.join(root, "plugins", name, "package.json")
  if (!existsSync(file)) fail(where, "missing")
  const manifest = JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>
  if (manifest.name !== name) fail(where, `name "${String(manifest.name)}" must equal the directory name "${name}"`)
  if (!NAME_PATTERN.test(name)) fail(where, `"${name}" is not a valid plugin name`)
  const version = manifest.version
  if (typeof version !== "string" || !SEMVER.test(version)) fail(where, `version "${String(version)}" is not semver`)
  const own = manifest[key]
  if (!isRecord(own)) fail(where, `missing "${key}" key`)
  const description = nonEmptyString(where, `${key}.description`, own.description)
  const category = nonEmptyString(where, `${key}.category`, own.category)
  const harnesses = own.harnesses
  if (!Array.isArray(harnesses) || harnesses.length === 0) fail(where, "harnesses must list at least one harness")
  for (const harness of harnesses) {
    if (!(KNOWN_HARNESSES as readonly unknown[]).includes(harness)) {
      fail(where, `unknown harness "${String(harness)}" (use ${KNOWN_HARNESSES.join(", ")})`)
    }
    if (!(config.harnesses as readonly unknown[]).includes(harness)) {
      fail(where, `harness "${String(harness)}" is not enabled in harness-kit.json (enabled: ${config.harnesses.join(", ")})`)
    }
  }
  const scope = own.scope === undefined ? undefined : nonEmptyString(where, `${key}.scope`, own.scope)
  for (const harness of KNOWN_HARNESSES) {
    if (!harnesses.includes(harness) && existsSync(path.join(root, "plugins", name, harness))) {
      fail(`plugins/${name}/${harness}`, `exists but "${harness}" is not in harnesses`)
    }
  }
  const discrepancies = own.discrepancies === undefined ? undefined : nonEmptyString(where, `${key}.discrepancies`, own.discrepancies)
  if (discrepancies !== undefined && /[\r\n]/.test(discrepancies)) fail(where, `"${key}.discrepancies" must be one line`)
  const options = readOptions(where, key, own.options)
  let claudeName: string | undefined
  if (own.claudeName !== undefined) {
    claudeName = nonEmptyString(where, `${key}.claudeName`, own.claudeName)
    if (!NAME_PATTERN.test(claudeName)) fail(where, `"${key}.claudeName" must be kebab-case`)
  }
  let piName: string | undefined
  if (own.piName !== undefined) {
    piName = nonEmptyString(where, `${key}.piName`, own.piName)
    if (!NPM_NAME.test(piName)) {
      fail(where, `"${key}.piName" must be an npm package name without a scope (the scope is "piScope"): lowercase letters, digits, ".", "_" or "-", starting with a letter or digit, got ${JSON.stringify(piName)}`)
    }
  }
  let author: { name: string; url?: string } | undefined
  if (manifest.author !== undefined) {
    const raw = manifest.author
    const authorName = typeof raw === "string" ? raw : isRecord(raw) ? raw.name : undefined
    if (typeof authorName !== "string" || !authorName.trim()) fail(where, '"author" must be a string or an object with a name')
    author = { name: authorName }
    // Existing repos may carry a url in package.json that was never emitted; it is read only once harness-kit.json sets claude.author.url.
    if (config.claude.author?.url !== undefined && isRecord(raw) && raw.url !== undefined) author.url = httpUrl(where, "author.url", raw.url)
  }
  const claude = readClaudeSettings(where, key, own.claude)
  const license = manifest.license === undefined ? undefined : nonEmptyString(where, "license", manifest.license)
  if (own.userConfig !== undefined && !isRecord(own.userConfig)) fail(where, `"${key}.userConfig" must be an object`)
  const userConfig = own.userConfig as Record<string, unknown> | undefined
  if (options && userConfig) fail(where, `set either "${key}.options" or "${key}.userConfig", not both: options generate the userConfig`)
  const selectedHarnesses = KNOWN_HARNESSES.filter((h) => harnesses.includes(h))
  const runtime = readRuntime(where, key, own.runtime, selectedHarnesses)
  const shared = readShared(where, key, own.shared, config)
  const prerequisites = readPrerequisites(where, `${key}.prerequisites`, own.prerequisites)
  const companions = readCompanions(where, `${key}.companions`, own.companions)
  // Keep canonical harness order so output does not depend on how the author ordered the list.
  return {
    name,
    version,
    description,
    category,
    harnesses: selectedHarnesses,
    scope,
    discrepancies,
    options,
    claudeName,
    piName,
    author,
    license,
    claude,
    userConfig,
    shared,
    runtime,
    prerequisites,
    companions,
  }
}

const DEPENDENCY_REF = /^[A-Za-z0-9][A-Za-z0-9._-]*(?:@[A-Za-z0-9][A-Za-z0-9._-]*)?$/

function readClaudeSettings(where: string, key: string, raw: unknown): ClaudeSettings | undefined {
  if (raw === undefined) return undefined
  const field = `${key}.claude`
  if (!isRecord(raw)) fail(where, `"${field}" must be an object`)
  const unknown = Object.keys(raw).filter((k) => !["dependencies", "homepage", "repository"].includes(k))
  if (unknown.length > 0) fail(where, `unknown key ${unknown.map((k) => `"${field}.${k}"`).join(", ")} (allowed: dependencies, homepage, repository)`)
  const settings: ClaudeSettings = {}
  if (raw.homepage !== undefined) settings.homepage = httpUrl(where, `${field}.homepage`, raw.homepage)
  if (raw.repository !== undefined) settings.repository = httpUrl(where, `${field}.repository`, raw.repository)
  if (raw.dependencies !== undefined) settings.dependencies = readDependencies(where, `${field}.dependencies`, raw.dependencies)
  return settings
}

function readDependencies(where: string, field: string, raw: unknown): ClaudeDependency[] {
  if (!Array.isArray(raw) || raw.length === 0) fail(where, `"${field}" must be a non-empty list of plugin names or { name, version, marketplace } objects`)
  const seen = new Set<string>()
  const dependencies = raw.map((item: unknown, index): ClaudeDependency => {
    const at = `${field}[${index}]`
    let id: string
    let dependency: ClaudeDependency
    if (typeof item === "string") {
      if (!DEPENDENCY_REF.test(item)) fail(where, `"${at}" must be a plugin name or "name@marketplace", got ${JSON.stringify(item)}`)
      id = item
      dependency = item
    } else if (isRecord(item)) {
      const extra = Object.keys(item).filter((k) => !["name", "version", "marketplace"].includes(k))
      if (extra.length > 0) fail(where, `"${at}" has unknown key ${extra.map((k) => `"${k}"`).join(", ")} (allowed: name, version, marketplace)`)
      const name = nonEmptyString(where, `${at}.name`, item.name)
      if (!DEPENDENCY_REF.test(name) || name.includes("@")) fail(where, `"${at}.name" must be a plugin name, got ${JSON.stringify(name)}`)
      dependency = { name }
      if (item.version !== undefined) dependency.version = nonEmptyString(where, `${at}.version`, item.version)
      if (item.marketplace !== undefined) dependency.marketplace = nonEmptyString(where, `${at}.marketplace`, item.marketplace)
      id = dependency.marketplace ? `${name}@${dependency.marketplace}` : name
    } else {
      fail(where, `"${at}" must be a plugin name or an object, got ${JSON.stringify(item)}`)
    }
    if (seen.has(id)) fail(where, `"${field}" lists "${id}" twice`)
    seen.add(id)
    return dependency
  })
  return dependencies
}

function readShared(where: string, key: string, raw: unknown, config: Config): string[] | undefined {
  if (raw === undefined) return undefined
  if (!Array.isArray(raw) || raw.length === 0) fail(where, `"${key}.shared" must be a non-empty list of items like "agents/name"`)
  for (const item of raw) {
    if (typeof item !== "string" || !SHARED_ITEM.test(item) || item.split("/").includes("..")) {
      fail(where, `"${key}.shared" item ${JSON.stringify(item)} must be a relative path like "agents/name"`)
    }
    const dir = item.split("/")[0]!
    if (!config.commonDirs.includes(dir)) fail(where, `shared item "${item}" is in "${dir}", which is not in commonDirs (${config.commonDirs.join(", ")})`)
  }
  if (new Set(raw).size !== raw.length) fail(where, `"${key}.shared" lists an item twice`)
  return raw as string[]
}

function readRuntime(where: string, key: string, raw: unknown, harnesses: Harness[]): RuntimeModuleName[] | undefined {
  if (raw === undefined || raw === false) return undefined
  const valid = raw === true || (Array.isArray(raw) && raw.length > 0 && raw.every((item) => typeof item === "string"))
  if (!valid) fail(where, `"${key}.runtime" must be true or a non-empty list of module names`)
  try {
    const modules = resolveRuntime(raw as boolean | string[], harnesses)
    return modules.length > 0 ? modules : undefined
  } catch (error) {
    return fail(where, `"${key}.runtime": ${error instanceof Error ? error.message : String(error)}`)
  }
}

function readOptions(where: string, key: string, raw: unknown): Record<string, PluginOption> | undefined {
  if (raw === undefined) return undefined
  if (!isRecord(raw)) fail(where, `"${key}.options" must be an object`)
  const options: Record<string, PluginOption> = {}
  for (const [name, value] of Object.entries(raw)) {
    if (!OPTION_NAME.test(name)) fail(where, `option "${name}" must be lowercase letters, digits and underscores`)
    if (!isRecord(value)) fail(where, `option "${name}" must be an object`)
    const description = nonEmptyString(where, `option "${name}" description`, value.description)
    if (typeof value.default !== "string") fail(where, `option "${name}" needs a string "default"`)
    options[name] = { description, default: value.default }
  }
  return options
}

/** Bare specifiers (neither relative nor `node:`) imported or re-exported by a module's source text. */
export function bareImports(source: string): string[] {
  const found: string[] = []
  const pattern = /(?:^|[;\n])\s*(?:(?:import|export)\b[^"'`;]*?\bfrom\s*|import\s*)["']([^"']+)["']/g
  for (const match of source.matchAll(pattern)) {
    const specifier = match[1] as string
    if (!specifier.startsWith(".") && !specifier.startsWith("/") && !specifier.startsWith("node:")) found.push(specifier)
  }
  return found
}

/**
 * OpenCode resolves host-provided packages (the plugin SDK, OpenTUI, Solid) only for modules reached through an import.
 * The files it loads first, the targets of the OpenCode package `exports`, must therefore import nothing bare.
 */
function checkOpencodeEntries(root: string, plugin: Plugin): void {
  if (!plugin.harnesses.includes("opencode")) return
  const dir = harnessDir(root, plugin, "opencode")
  for (const target of Object.values(opencodeExports(root, plugin))) {
    const file = path.join(dir, target)
    if (!existsSync(file)) continue
    const bare = bareImports(readFileSync(file, "utf8"))
    if (bare.length > 0) {
      fail(`plugins/${plugin.name}/opencode/${target.replace("./", "")}`, `entry file imports ${bare.map((x) => `"${x}"`).join(", ")} directly; move it behind a shim (the entry re-exports from another module)`)
    }
  }
}

/** The name of a plugin's pi package: `<piScope>/<piName>`, or `<piScope>/<piPrefix><plugin name>` without `piName`. */
export function piPackageName(plugin: Pick<Plugin, "name" | "piName">, config: Pick<Config, "piScope" | "piPrefix">): string {
  return `${config.piScope}/${plugin.piName ?? `${config.piPrefix}${plugin.name}`}`
}

/** Every pi package name fits npm's length limit and belongs to one plugin. */
function checkPiNames(plugins: readonly Plugin[], config: Config): void {
  const owners = new Map<string, string>()
  for (const plugin of plugins.filter((item) => item.harnesses.includes("pi") || item.piName !== undefined)) {
    const where = `plugins/${plugin.name}/package.json`
    const name = piPackageName(plugin, config)
    if (name.length > NPM_NAME_MAX) fail(where, `pi package name "${name}" is longer than npm's ${NPM_NAME_MAX} characters`)
    const owner = owners.get(name)
    if (owner !== undefined) fail(where, `pi package name "${name}" is also the name of plugin "${owner}"; set a different "${config.pluginKey}.piName"`)
    owners.set(name, plugin.name)
  }
}

export function readPlugins(root: string, config: Config): Plugin[] {
  const plugins = listDirs(path.join(root, "plugins")).map((name) => readPlugin(root, name, config))
  for (const plugin of plugins) {
    checkOpencodeEntries(root, plugin)
    resolveShared(root, plugin, config)
  }
  checkPiNames(plugins, config)
  checkCompanions(plugins, config)
  return plugins
}

/** A companion is another package: not the plugin's own pi package, and not one that pi itself supplies. */
function checkCompanions(plugins: readonly Plugin[], config: Config): void {
  for (const plugin of plugins) {
    const where = `plugins/${plugin.name}/package.json`
    for (const companion of plugin.companions ?? []) {
      if (PI_HOST_PACKAGES.includes(companion.package)) fail(where, `companion "${companion.package}" is supplied by pi itself; list only pi packages that are installed on their own`)
      if (companion.package === piPackageName(plugin, config)) fail(where, `companion "${companion.package}" is this plugin's own pi package`)
    }
  }
}

const pluginDir = (root: string, plugin: Plugin) => path.join(root, "plugins", plugin.name)
const harnessDir = (root: string, plugin: Plugin, harness: Harness) => path.join(pluginDir(root, plugin), harness)

/** Matches `<name>.<harness>.<ext>`: a copy of `<name>.<ext>` that only that harness gets. */
const VARIANT = new RegExp(`^(.+)\\.(${KNOWN_HARNESSES.join("|")})(\\.[^./]+)$`)

/**
 * OMP injects a plugin rule into the system prompt only when its front matter says `alwaysApply: true`, and the pi
 * rules loader reads the same field.
 */
const ALWAYS_APPLY = "---\nalwaysApply: true\n---\n\n"

/** The pi rules loader, vendored into `<pi tree>/_kit/` when the tree has rules. pi has no rules resource of its own. */
const PI_RULES_LOADER = "rules.ts"

/** The OMP variant of a plain file: `x.md` gives `x.omp.md`. */
const ompVariant = (file: string) => file.replace(/(\.[^./]+)$/, ".omp$1")

/** A pi-subagents agent definition: Markdown under agents/, except chains (`x.chain.md`). */
const isPiAgent = (file: string) => file.endsWith(".md") && !file.endsWith(".chain.md")

/**
 * The common files one harness receives, as [source, destination] pairs relative to common/<dir>.
 * `x.<harness>.md` replaces `x.md` in that harness and appears in no other.
 */
function commonFilesFor(files: string[], harness: Harness): Array<[string, string]> {
  const variantOf = (file: string) => {
    const match = VARIANT.exec(path.basename(file))
    return match ? { harness: match[2], plain: path.join(path.dirname(file), `${match[1]}${match[3]}`) } : undefined
  }
  const overridden = new Set(files.flatMap((file) => (variantOf(file)?.harness === harness ? [variantOf(file)!.plain] : [])))
  const picked: Array<[string, string]> = []
  for (const file of files) {
    const variant = variantOf(file)
    if (!variant) {
      if (!overridden.has(file)) picked.push([file, file])
    } else if (variant.harness === harness) picked.push([file, variant.plain])
  }
  return picked
}

/** The plain (variant-free) name of a file: `x.claude.md` and `x.md` both give `x.md`. */
function plainName(file: string): string {
  const match = VARIANT.exec(path.basename(file))
  return match ? path.join(path.dirname(file), `${match[1]}${match[3]}`) : file
}

/** Whether a file of the shared directory belongs to the item `rest` (the part after the kind directory). */
function belongsToItem(file: string, rest: string): boolean {
  if (file === rest || file.startsWith(`${rest}/`)) return true
  if (stripExtension(file) === rest) return true
  return stripExtension(plainName(file)) === rest
}

/** Shared files a plugin takes, by kind directory: paths relative to <sharedDir>/<dir>. Throws on a missing item or a clash. */
function resolveShared(root: string, plugin: Plugin, config: Config): Map<string, string[]> {
  const taken = new Map<string, string[]>()
  const common = path.join(pluginDir(root, plugin), "common")
  for (const item of plugin.shared ?? []) {
    const [dir, ...parts] = item.split("/") as [string, ...string[]]
    const rest = parts.join("/")
    const base = path.join(root, config.sharedDir, dir)
    const files = listFiles(base).filter((file) => belongsToItem(file, rest))
    if (files.length === 0) fail(`plugins/${plugin.name}/package.json`, `shared item "${item}" not found in ${config.sharedDir}/${dir}/`)
    const own = new Set(listFiles(path.join(common, dir)).map(plainName))
    for (const file of files) {
      if (own.has(plainName(file))) {
        fail(`plugins/${plugin.name}`, `shared item "${item}" clashes with its own common/${dir}/${plainName(file)}; remove one of them`)
      }
    }
    taken.set(dir, [...(taken.get(dir) ?? []), ...files])
  }
  return taken
}

/** Header for a copy of a shared Markdown file, placed after any front matter so the front matter still parses. */
function withSharedHeader(text: string, note: string): string {
  const front = /^---\r?\n[\s\S]*?\r?\n---\r?\n?/.exec(text)
  if (!front) return `${note}\n\n${text}`
  const head = front[0].endsWith("\n") ? front[0] : `${front[0]}\n`
  return `${head}${note}\n${text.slice(front[0].length)}`
}

function ownedCopies(root: string, plugin: Plugin, config: Config): Output[] {
  const common = path.join(pluginDir(root, plugin), "common")
  const shared = resolveShared(root, plugin, config)
  const outputs: Output[] = []
  for (const harness of plugin.harnesses) {
    for (const dir of config.commonDirs) {
      const own = listFiles(path.join(common, dir))
      const taken = shared.get(dir) ?? []
      const files = [...own, ...taken].sort()
      const originOf = (file: string) => (taken.includes(file) ? path.join(root, config.sharedDir, dir, file) : path.join(common, dir, file))
      for (const [source, dest] of commonFilesFor(files, harness)) {
        const isShared = taken.includes(source)
        const origin = originOf(source)
        let contents: string | Buffer = readFileSync(origin)
        if (harness === "pi" && dir === "agents" && source === dest && isPiAgent(dest)) {
          // pi-subagents has its own front matter. Translate the file OMP gets: its variant, which lists tools, when there is one.
          const from = files.includes(ompVariant(source)) ? originOf(ompVariant(source)) : origin
          contents = piAgent(readFileSync(from, "utf8"), {
            name: stripExtension(path.basename(dest)),
            from: path.relative(root, from).split(path.sep).join("/"),
            generatedBy: config.generatedBy,
          })
        } else {
          if ((harness === "omp" || harness === "pi") && dir === "rules" && !contents.subarray(0, 3).equals(Buffer.from("---"))) {
            contents = ALWAYS_APPLY + contents.toString("utf8")
          }
          if (isShared && source.endsWith(".md")) {
            const note = `<!-- Generated by ${config.generatedBy} from ${config.sharedDir}/${dir}/${source}. Do not edit. -->`
            contents = withSharedHeader(contents.toString("utf8"), note)
          }
        }
        outputs.push({
          file: path.join(harnessDir(root, plugin, harness), dir, dest),
          contents,
          executable: (statSync(origin).mode & OWNER_EXEC) !== 0,
        })
      }
    }
  }
  return outputs
}

/** The opted-in runtime modules, copied into each harness tree's `_kit/` directory. */
function runtimeCopies(root: string, plugin: Plugin, config: Config): Output[] {
  return (plugin.runtime ?? []).map((name) => {
    const { harness, file, contents } = vendoredSource(name, config.generatedBy)
    return { file: path.join(harnessDir(root, plugin, harness), RUNTIME_DIR, file), contents }
  })
}

/** The pi rules loader when the plugin's pi tree receives at least one rule. */
function piRulesLoader(root: string, plugin: Plugin, copies: readonly Output[], config: Config): Output[] {
  if (!plugin.harnesses.includes("pi")) return []
  const rules = path.join(harnessDir(root, plugin, "pi"), "rules") + path.sep
  if (!copies.some((copy) => copy.file.startsWith(rules) && /\.mdc?$/.test(copy.file))) return []
  return [{ file: path.join(harnessDir(root, plugin, "pi"), RUNTIME_DIR, PI_RULES_LOADER), contents: vendoredFile("pi", PI_RULES_LOADER, config.generatedBy) }]
}

/** The contents of a tree's `_kit/prereqs.json`, which the vendored check reads. Only the pi tree's list has the companions. */
export function prerequisiteData(plugin: Pick<Plugin, "name" | "prerequisites" | "companions">, harness: Harness): { plugin: string; prerequisites: Prerequisite[]; companions?: Companion[] } {
  return { plugin: plugin.name, prerequisites: plugin.prerequisites ?? [], ...(harness === "pi" && plugin.companions ? { companions: plugin.companions } : {}) }
}

/** Whether a tree gets the check: for prerequisites in the pi and OMP trees, and for companions in the pi tree. */
export const hasPrerequisiteCheck = (plugin: Pick<Plugin, "prerequisites" | "companions">, harness: Harness): boolean =>
  PREREQS_HARNESSES.includes(harness) && (plugin.prerequisites !== undefined || (harness === "pi" && plugin.companions !== undefined))

/** The prerequisite check and the plugin's list, in each tree that gets the check. */
function prerequisiteFiles(root: string, plugin: Plugin, config: Config): Output[] {
  return plugin.harnesses.filter((harness) => hasPrerequisiteCheck(plugin, harness)).flatMap((harness) => [
    { file: path.join(harnessDir(root, plugin, harness), RUNTIME_DIR, PREREQS_MODULE), contents: vendoredFile("pi", PREREQS_MODULE, config.generatedBy) },
    { file: path.join(harnessDir(root, plugin, harness), RUNTIME_DIR, PREREQS_DATA), contents: json(prerequisiteData(plugin, harness)) },
  ])
}

/** `./_kit/prereqs.ts` when this build vendors it into the tree; `files` are relative to the tree. */
const prereqsEntry = (files: readonly string[]) => (files.includes(`${RUNTIME_DIR}/${PREREQS_MODULE}`) ? [`./${RUNTIME_DIR}/${PREREQS_MODULE}`] : [])

/** Files a published pi tree takes from the plugin (changelog) and the repo (licence), copied byte for byte. */
const PUBLISH_COPIES = [
  ["CHANGELOG.md", "plugin"],
  ["LICENSE", "repo"],
] as const

/** Whether the pi tree gets a README.md: a published one does, and so does one whose plugin names companions. */
const hasPiReadme = (plugin: Plugin, config: Config) => config.pi.publish || plugin.companions !== undefined

/** Root files of a harness tree that the build owns: the pi README and the copies a published pi tree takes. */
function ownedRootFiles(plugin: Plugin, harness: Harness, config: Config): string[] {
  if (harness !== "pi") return []
  return [...(hasPiReadme(plugin, config) ? ["README.md"] : []), ...(config.pi.publish ? PUBLISH_COPIES.map(([file]) => file) : [])]
}

/** The "Works with" section of the pi README: each companion, what it is for, and how to install it. */
function worksWith(companions: readonly Companion[]): string {
  const cellText = (text: string) => text.replaceAll("|", "\\|")
  const rows = companions.map((item) => `| \`${item.package}\` | ${item.required ? "yes" : "no"} | ${cellText(item.for)} | \`pi install npm:${item.package}\` |`)
  return ["## Works with", "", "This package works with these pi packages. Install them next to it.", "", "| Package | Required | For | Install |", "| --- | --- | --- | --- |", ...rows, ""].join("\n")
}

/**
 * The pi tree's README.md: the plugin's own README.md, byte for byte, then the "Works with" section when it names
 * companions. A plugin without a README.md gets a heading and its description in front of the section.
 */
function piReadme(root: string, plugin: Plugin, config: Config): string | Buffer | undefined {
  const source = path.join(pluginDir(root, plugin), "README.md")
  const own = existsSync(source) ? readFileSync(source) : undefined
  if (!plugin.companions) return own
  const head = own ? own.toString("utf8").replace(/\s*$/, "\n") : `# ${piPackageName(plugin, config)}\n\n${plugin.description}\n`
  return `${head}\n${worksWith(plugin.companions)}`
}

function piRootCopies(root: string, plugin: Plugin, config: Config): Output[] {
  if (!plugin.harnesses.includes("pi")) return []
  const tree = harnessDir(root, plugin, "pi")
  const readme = hasPiReadme(plugin, config) ? piReadme(root, plugin, config) : undefined
  const copies = config.pi.publish
    ? PUBLISH_COPIES.flatMap(([file, from]) => {
        const source = path.join(from === "plugin" ? pluginDir(root, plugin) : root, file)
        return existsSync(source) ? [{ file: path.join(tree, file), contents: readFileSync(source) }] : []
      })
    : []
  return [...(readme !== undefined ? [{ file: path.join(tree, "README.md"), contents: readme }] : []), ...copies]
}

/** What a published pi package takes from the repo's root package.json. */
type PublishSettings = { license?: string; repository: string; homepage?: unknown; bugs?: unknown }

const GITHUB_SHORTHAND = /^(?:github:)?([A-Za-z0-9_.-]+)\/([A-Za-z0-9_.-]+?)(?:\.git)?$/

/** The root package.json fields every published pi package carries. npm provenance checks `repository` against the publishing repo. */
function readPublishSettings(root: string): PublishSettings {
  const where = "package.json"
  const file = path.join(root, "package.json")
  if (!existsSync(file)) fail(where, 'missing; "pi.publish" takes "repository" from the root package.json')
  const manifest = JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>
  const raw = isRecord(manifest.repository) ? manifest.repository.url : manifest.repository
  if (raw === undefined) fail(where, '"repository" is required when "pi.publish" is on, because npm provenance checks it against the repository that publishes')
  const given = nonEmptyString(where, "repository", raw)
  const shorthand = GITHUB_SHORTHAND.exec(given)
  const repository = shorthand ? `git+https://github.com/${shorthand[1]}/${shorthand[2]}.git` : given
  if (!/^(?:git\+)?https:\/\//.test(repository)) fail(where, `"repository" must be a GitHub shorthand ("owner/repo") or an https URL, got ${JSON.stringify(given)}`)
  const license = manifest.license === undefined ? undefined : nonEmptyString(where, "license", manifest.license)
  return { license, repository, homepage: manifest.homepage, bugs: manifest.bugs }
}

/** Packages pi supplies to extensions. A published package lists the ones it imports as peers, never as dependencies. */
const PI_HOST_PACKAGES = ["@earendil-works/pi-agent-core", "@earendil-works/pi-ai", "@earendil-works/pi-coding-agent", "@earendil-works/pi-tui", "typebox"]

const packageOf = (specifier: string) => specifier.split("/").slice(0, specifier.startsWith("@") ? 2 : 1).join("/")

/** `dependencies` of a published pi package: the npm package and range of each `install.npm` prerequisite, by name. */
function prerequisiteDependencies(plugin: Plugin): Record<string, string> {
  const where = `plugins/${plugin.name}/package.json`
  const found = new Map<string, string>()
  for (const { install } of plugin.prerequisites ?? []) {
    const spec = install.npm === undefined ? undefined : npmSpec(install.npm)
    if (!spec) continue
    if (PI_HOST_PACKAGES.includes(spec.name)) fail(where, `prerequisite package "${spec.name}" is supplied by pi, so a published package must not list it in "dependencies"`)
    const other = found.get(spec.name)
    if (other !== undefined && other !== spec.range) fail(where, `prerequisites give "${spec.name}" two ranges, "${other}" and "${spec.range}"; "dependencies" takes one`)
    found.set(spec.name, spec.range)
  }
  return Object.fromEntries([...found].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)))
}

/**
 * The npm fields of a published pi package. `files` lists every top-level entry the tree ships, so nothing else is
 * packed: not package.json (npm always packs it), node_modules or a dot-entry such as `.DS_Store`. `own` are the tree's
 * hand-authored files, which are scanned for imports of the host packages. An npm prerequisite becomes a dependency,
 * so installing the package puts its bin in `node_modules/.bin`, where the prerequisite check looks first.
 */
function publishFields(root: string, plugin: Plugin, publish: PublishSettings, files: readonly string[], own: readonly string[]): Record<string, unknown> {
  const license = plugin.license ?? publish.license
  if (license === undefined) fail(`plugins/${plugin.name}/package.json`, '"license" is required when "pi.publish" is on; set it here or in the root package.json')
  const dir = harnessDir(root, plugin, "pi")
  const imported = new Set(
    own.filter((file) => MODULE_EXTENSION.test(file) && !file.startsWith("node_modules/")).flatMap((file) => bareImports(readFileSync(path.join(dir, file), "utf8")).map(packageOf)),
  )
  const companions = plugin.companions ?? []
  const peers = [...PI_HOST_PACKAGES.filter((name) => imported.has(name)).map((name): [string, string] => [name, "*"]), ...companions.map((item): [string, string] => [item.package, item.range ?? "*"])]
  peers.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  const shipped = [...new Set(files.map((file) => file.split("/")[0] as string))].filter((entry) => entry !== "package.json" && entry !== "node_modules" && !entry.startsWith("."))
  const dependencies = prerequisiteDependencies(plugin)
  return {
    license,
    repository: { type: "git", url: publish.repository, directory: `plugins/${plugin.name}/pi` },
    ...(publish.homepage !== undefined ? { homepage: publish.homepage } : {}),
    ...(publish.bugs !== undefined ? { bugs: publish.bugs } : {}),
    files: shipped.sort(),
    publishConfig: { access: "public", provenance: true },
    ...(Object.keys(dependencies).length > 0 ? { dependencies } : {}),
    ...(peers.length > 0 ? { peerDependencies: Object.fromEntries(peers) } : {}),
    ...(companions.length > 0
      ? { peerDependenciesMeta: Object.fromEntries([...companions].sort((a, b) => (a.package < b.package ? -1 : 1)).map((item) => [item.package, { optional: true }])) }
      : {}),
  }
}

function ompExtensions(root: string, plugin: Plugin): string[] {
  const dir = path.join(harnessDir(root, plugin, "omp"), "extensions")
  if (!existsSync(dir)) return []
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isFile() && MODULE_EXTENSION.test(entry.name))
    .map((entry) => `./extensions/${entry.name}`)
    .sort()
}

/** Paths, relative to a harness tree and posix-style, of the outputs that land in it. */
function generatedIn(root: string, plugin: Plugin, harness: Harness, outputs: readonly Output[]): string[] {
  const prefix = harnessDir(root, plugin, harness) + path.sep
  return outputs.filter((output) => output.file.startsWith(prefix)).map((output) => output.file.slice(prefix.length).split(path.sep).join("/"))
}

/** The hand-authored files of a harness tree: everything outside the directories and root files the build owns. */
function ownFiles(root: string, plugin: Plugin, harness: Harness, config: Config): string[] {
  const hasMcpSource = commonMcpServers(root, plugin) !== undefined
  const owned = [...config.commonDirs, RUNTIME_DIR, ...(hasMcpSource ? ["mcp-servers"] : [])]
  const ownedRoot = [...ownedRootFiles(plugin, harness, config), ...(hasMcpSource && harness === "pi" ? ["mcp-servers.ts"] : [])]
  return listFiles(harnessDir(root, plugin, harness)).filter((file) => !owned.some((dir) => file.startsWith(`${dir}/`)) && !ownedRoot.includes(file))
}

/** What a harness tree holds after this build: its hand-authored files, plus `generated`. */
function treeFiles(root: string, plugin: Plugin, harness: Harness, generated: string[], config: Config): string[] {
  return [...new Set([...ownFiles(root, plugin, harness, config), ...generated])].sort()
}

/**
 * The `pi` key of the pi package.json: only the resources the tree ships. An explicit manifest turns off pi's
 * conventional directories, so commands are listed as prompts and agents under pi-subagents' `subagents.agents`.
 * pi loads a package whose manifest lists none of `extensions`, `skills`, `prompts` and `themes` as one extension at
 * the package root, which fails to start (pi 1.6.0). Such a manifest, as for a package of agents only, gets
 * `extensions: []`.
 */
function piResources(files: readonly string[]): Record<string, unknown> {
  const extensions = [
    ...files.filter((file) => /^extensions\/[^/]+$/.test(file) && MODULE_EXTENSION.test(file)),
    ...files.filter((file) => file === "mcp-servers.ts"),
    ...files.filter((file) => file === `${RUNTIME_DIR}/${PI_RULES_LOADER}`),
  ].map((file) => `./${file}`)
  extensions.push(...prereqsEntry(files))
  const has = (accept: (file: string) => boolean) => files.some(accept)
  const skills = has((file) => /^skills\/.+\/SKILL\.md$/.test(file))
  const prompts = has((file) => /^commands\/[^/]+\.md$/.test(file))
  return {
    ...(extensions.length > 0 || (!skills && !prompts) ? { extensions } : {}),
    ...(skills ? { skills: ["./skills"] } : {}),
    ...(prompts ? { prompts: ["./commands"] } : {}),
    ...(has((file) => file.startsWith("agents/") && isPiAgent(file)) ? { subagents: { agents: ["./agents"] } } : {}),
  }
}

function opencodeFile(root: string, plugin: Plugin, base: "index" | "tui"): string | undefined {
  const dir = harnessDir(root, plugin, "opencode")
  return [`${base}.ts`, `${base}.js`].find((file) => existsSync(path.join(dir, file)))
}

/**
 * The `exports` map of the OpenCode package: the server entry, plus `./tui` when the tree has a TUI half.
 * A TUI-only tree has no server entry, so `.` is left out rather than pointing at a missing file.
 */
function opencodeExports(root: string, plugin: Plugin): Record<string, string> {
  const server = opencodeFile(root, plugin, "index")
  const tui = opencodeFile(root, plugin, "tui")
  return {
    ...(server || !tui ? { ".": `./${server ?? "index.js"}` } : {}),
    ...(tui ? { "./tui": `./${tui}` } : {}),
  }
}

