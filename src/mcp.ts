import { isRecord, json } from "./util"

export type McpServer = Record<string, unknown>
export type McpServers = Record<string, McpServer>

/** Required MCP credentials are explicitly named in `requiredEnv`; placeholder-looking values are not enough to require a key. */
export function requiredEnvironment(server: McpServer): string[] {
  return Array.isArray(server.requiredEnv) ? server.requiredEnv.filter((key): key is string => typeof key === "string") : []
}

function withoutAuthoringFields(server: McpServer): McpServer {
  const { enabled: _enabled, optionalHeaders: _optionalHeaders, requiredEnv: _requiredEnv, ...config } = server
  const optionalVariables = new Set(Object.values(server.optionalHeaders ?? {}).filter((value): value is string => typeof value === "string"))
  if (isRecord(config.headers)) {
    config.headers = Object.fromEntries(Object.entries(config.headers).filter(([, value]) => {
      if (typeof value !== "string") return true
      const placeholders = [...value.matchAll(/\$\{([A-Za-z_][A-Za-z0-9_]*)\}/g)].map((match) => match[1]!)
      return !placeholders.some((key) => optionalVariables.has(key))
    }))
  }
  if (isRecord(config.headers) && Object.keys(config.headers).length === 0) delete config.headers
  return config
}

function staticallyEnabled(servers: McpServers): McpServers {
  return Object.fromEntries(Object.entries(servers)
    .filter(([, server]) => server.enabled !== false)
    .map(([name, server]) => [name, withoutAuthoringFields(server)]))
}

export function mcpServersForClaude(servers: McpServers): McpServers {
  return staticallyEnabled(servers)
}

function ompTransport(pluginName: string, serverName: string, server: McpServer): McpServer {
  const type = server.type
  const command = typeof server.command === "string" && server.command.length > 0
  const url = typeof server.url === "string" && server.url.length > 0
  if (type === undefined) {
    if (command) return { ...server, type: "stdio" }
    if (url) return { ...server, type: "streamable-http" }
    throw new Error(`plugin "${pluginName}" MCP server "${serverName}" needs a command or url for OMP`)
  }
  if (type === "http") {
    if (!url) throw new Error(`plugin "${pluginName}" MCP server "${serverName}" with type "http" needs a url for OMP`)
    return { ...server, type: "streamable-http" }
  }
  if (type === "stdio" && command) return server
  if ((type === "streamable-http" || type === "sse") && url) return server
  throw new Error(`plugin "${pluginName}" MCP server "${serverName}" has unsupported OMP transport ${JSON.stringify(type)} or is missing its ${type === "stdio" ? "command" : "url"}`)
}

export function mcpServersForOmp(servers: McpServers, pluginName: string): McpServers {
  return Object.fromEntries(Object.entries(servers)
    .filter(([, server]) => server.enabled !== false && requiredEnvironment(server).length === 0)
    .map(([name, server]) => [name, ompTransport(pluginName, name, withoutAuthoringFields(server))]))
}

export function piMcpExtension(servers: McpServers): string {
  const active = staticallyEnabled(servers)
  const required = Object.fromEntries(Object.entries(servers)
    .filter(([, server]) => server.enabled !== false)
    .map(([name, server]) => [name, requiredEnvironment(server)])
    .filter(([, keys]) => (keys as string[]).length > 0))
  const optionalHeaders = Object.fromEntries(Object.entries(servers)
    .filter(([, server]) => server.enabled !== false)
    .map(([name, server]) => [name, server.optionalHeaders ?? {}])
    .filter(([, headers]) => isRecord(headers) && Object.keys(headers).length > 0))
  return [
    "// Generated by harness-kit. Do not edit.",
    `const servers = ${json(active).trim()} as const`,
    `const requiredEnvironment = ${json(required).trim()} as const`,
    `const optionalHeaders = ${json(optionalHeaders).trim()} as const`,
    "",
    "const expand = (value: unknown): unknown => {",
    "  if (typeof value === \"string\") return value.replace(/\\$\\{([A-Za-z_][A-Za-z0-9_]*)\\}/g, (match, key: string) => process.env[key] ?? match)",
    "  if (Array.isArray(value)) return value.map(expand)",
    "  if (value && typeof value === \"object\") return Object.fromEntries(Object.entries(value).map(([key, nested]) => [key, expand(nested)]))",
    "  return value",
    "}",
    "",
    "export default function registerMcpServers(pi: { registerMcpServer(name: string, config: Record<string, unknown>): unknown }): void {",
    "  for (const [name, config] of Object.entries(servers)) {",
    "    const keys = requiredEnvironment[name as keyof typeof requiredEnvironment] ?? []",
    "    if (keys.some((key) => !process.env[key])) continue",
    "    const resolved = expand(config) as Record<string, unknown>",
    "    const headers = { ...(resolved.headers as Record<string, string> | undefined) }",
    "    for (const [header, variable] of Object.entries(optionalHeaders[name as keyof typeof optionalHeaders] ?? {})) {",
    "      const value = process.env[variable as string]",
    "      if (value) headers[header] = value",
    "    }",
    "    const registration = Object.keys(headers).length > 0 ? { ...resolved, headers } : resolved",
    "    pi.registerMcpServer(name, registration)",
    "  }",
    "}",
    "",
  ].join("\n")
}
